// Exercise the shipped adapter with real fits, report renderer and share codecs.
// Only DOM access and the native Run button are doubled; no browser layout claims.
function setup(data = rows) {
  const fields = Object.fromEntries(Object.entries({
    data: data.map((r, i) => ['Study ' + i, r.tp, r.fp, r.fn, r.tn].join(', ')).join('\n'),
    title: 'Original', method: 'fixed', cc: 'all', cov: '', example: 'generic'
  }).map(([key, value]) => ['f-' + key, { value }]));
  fields['f-example'].options = [{ value: 'generic' }];
  fields['analysis-stale'] = { hidden: true };
  let runs = 0;
  fields['btn-run'] = { click() { runs++; } };
  const axes = ['0', '1', false, '0', '1', false].map(value => ({
    type: typeof value === 'boolean' ? 'checkbox' : 'number', value,
    checked: value === false ? false : undefined, dispatchEvent() {}
  }));
  const status = { textContent: '' }, handlers = {};
  const fit = B.fit(data, { method: 'fixed' });
  const deeks = B.deeksTest(data);
  const window = {
    location: { hash: '' },
    addEventListener(type, handler) { handlers[type] = handler; },
    AlmFeatures: { register() {}, open() {} },
    AlmFeaturesState: { entryLog: [], provenance: [] },
    AlmShare: S, AlmText: T,
    alm: { urlState: { withoutWrites: fn => fn() } },
    __almBivariate: () => fit, __almDeeks: () => deeks, __almMetaRegression: () => null
  };
  const document = {
    getElementById: id => fields[id] || null,
    querySelectorAll: selector => selector === '#alm-axis-mount input' ? axes : [],
    querySelector: selector => selector.includes('share-status') ? status :
      selector === '#fagan-host svg text:last-child' ? { textContent: 'pre 20% → +test 69%, −test 5%' } : null
  };
  vm.runInNewContext(source, { window, document, URL, Event });
  const spec = window.AlmDTAFeatures;
  return { spec, window, status, fields, deeks, runs: () => runs,
    async navigate(hash) {
      window.location.hash = hash;
      await handlers.hashchange({ newURL: 'https://example.test/dta-sroc/' + hash });
    }
  };
}

function report(h) {
  const results = h.spec.text.results();
  assert.ok(results && Number.isFinite(results.sens), 'a valid bivariate fit exists');
  const ctx = { app: 'dta-sroc', build: { version: 'test', shortSha: 'abcdef0' }, entryLog: [] };
  const rendered = T.render(h.spec.text.templates, results, ctx);
  assert.equal(T.audit(rendered, results, { ctx }).ok, true);
  return rendered;
}

test('DTA report survives an unavailable Deeks test with equal effective sample sizes', () => {
  const h = setup([
    { tp: 24, fp: 8, fn: 8, tn: 24 },
    { tp: 25, fp: 6, fn: 7, tn: 26 },
    { tp: 20, fp: 5, fn: 12, tn: 27 },
    { tp: 28, fp: 10, fn: 4, tn: 22 }
  ]);
  assert.equal(h.deeks, null, 'real engine cannot estimate the Deeks slope');
  const rendered = report(h);
  assert.match(rendered.results.text, /summary sensitivity was/);
  assert.doesNotMatch(rendered.methods.text, /Deeks’ test regressed/);
  assert.doesNotMatch(rendered.results.text, /Deeks’ test p/);
});

test('DTA report control retains an estimable Deeks test and its degrees of freedom', () => {
  const h = setup();
  assert.ok(Number.isFinite(h.deeks.p));
  const rendered = report(h);
  assert.match(rendered.methods.text, /2 residual degrees of freedom/);
  assert.match(rendered.results.text, /Deeks’ test p =/);
});

test('DTA same-page navigation restores the v2 links generated by Share this analysis', async () => {
  const h = setup(), state = { ...h.spec.share.get(), title: 'Restored v2', method: 'ml' };
  const provenance = [{ label: 'Source', confirmed: true }];
  const packed = await S.encodeV2(S.payload('dta-sroc', state, provenance));
  await h.navigate('#a2=' + packed);
  assert.equal(h.fields['f-title'].value, state.title);
  assert.equal(h.fields['f-method'].value, state.method);
  assert.deepEqual(h.window.AlmFeaturesState.provenance, provenance);
  assert.equal(h.runs(), 1);
  assert.match(h.status.textContent, /Analysis restored/);
});

test('DTA same-page legacy share links still restore', async () => {
  const h = setup(), state = { ...h.spec.share.get(), title: 'Restored legacy' };
  await h.navigate('#s=' + await S.encode('dta-sroc', state, []));
  assert.equal(h.fields['f-title'].value, state.title);
  assert.equal(h.runs(), 1);
});

test('DTA same-page corrupt v2 links report failure without changing the analysis', async () => {
  const h = setup(), before = JSON.stringify(h.spec.share.get());
  await h.navigate('#a2=invalid');
  assert.equal(JSON.stringify(h.spec.share.get()), before);
  assert.equal(h.runs(), 0);
  assert.match(h.status.textContent, /could not be opened.*Nothing was changed/);
});

test('DTA same-page v2 build mismatch preserves inputs and requests the existing reload confirmation flow', async () => {
  const h = setup(), before = JSON.stringify(h.spec.share.get());
  const payload = S.payload('dta-sroc', { ...h.spec.share.get(), title: 'Other build' }, []);
  payload.build = { ...payload.build, version: '0.0.0-review', sha: 'f'.repeat(40) };
  await h.navigate('#a2=' + await S.encodeV2(payload));
  assert.equal(JSON.stringify(h.spec.share.get()), before);
  assert.equal(h.runs(), 0);
  assert.match(h.status.textContent, /version|build/i);
  assert.match(h.status.textContent, /reload/i);
});

test('DTA navigation control ignores native hashes and cancels an older pending decode', async () => {
  const h = setup();
  let release;
  h.window.AlmShare = { ...S, decode: () => new Promise(resolve => { release = resolve; }) };
  const pending = h.navigate('#s=delayed');
  await h.navigate('#native-state');
  release({ ok: true, state: { ...h.spec.share.get(), title: 'Obsolete' }, provenance: [] });
  await pending;
  assert.equal(h.fields['f-title'].value, 'Original');
  assert.equal(h.runs(), 0);
});
