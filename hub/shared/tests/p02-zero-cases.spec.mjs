import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';
const fixture=JSON.parse(readFileSync(new URL('unit/p02-zero-cases-reference.json',import.meta.url)));
const f=fixture.cases.find(f=>f.name==='cc/nonreference/h/2stage');
const csv=['study,dose,cases,n,logrr,se,type',...f.rows.map(r=>[r.id,r.dose,r.cases,r.n,r.logrr,r.se,r.type].join(','))].join('\n');
test('zero category is retained on page, in live R input, and in JSON export',async({page})=>{
 await page.goto('/dose-response-ma/index.html');
 await page.locator('#f-cov').selectOption('h');
 await page.locator('#f-method').selectOption('FE');
 await page.locator('#f-data').fill(csv);
 await page.locator('#btn-run').click();
 await expect(page.locator('#headline')).toContainText('k = 3 studies');
 await expect(page.locator('#headline')).toContainText('-0.0463');
 await expect(page.locator('#msgs')).toContainText('zero-case category retained');
 const r=await page.evaluate(()=>window._almLastDoseResponse());
 expect(Math.abs(r.slope-f.slope)).toBeLessThanOrEqual(1e-6);
 const live=await page.evaluate(()=>window._almLastDoseResponseValidation());
 expect(JSON.stringify(live)).toContain('zero-category');
 const download=page.waitForEvent('download');
 await page.locator('#alm-export-mount [data-action="json"]').click();
 const artifact=await download;
 const exported=JSON.parse(readFileSync(await artifact.path(),'utf8'));
 expect(exported).toEqual(r);
 expect(exported.warnings.join(' ')).toContain('no continuity correction');
 await page.locator('#f-cov').selectOption('gl');
 await expect(page.locator('#msgs')).toContainText('zero cases prevent Greenland-Longnecker');
 expect(await page.evaluate(()=>window._almLastDoseResponse())).toBeNull();
 await expect(page.locator('#headline')).toBeEmpty();
});
