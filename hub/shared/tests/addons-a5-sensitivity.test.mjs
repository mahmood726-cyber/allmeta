// Lane A5 (node --test): shared/sensitivity-v1.js against the metafor 5.2-1 reference, the
// manifest built from that comparison, and the module's refusals. Every check is also shown
// able to fail (perturbed reference, perturbed module, wrong manifest).
import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {ROOT, REFERENCE, MANIFEST, TOL, loadApi, readText, sha256Lf, runParity, buildManifest, compareCombo, compareValue} from './addons-a5-parity.mjs';

const S = loadApi();
const refText = readText(REFERENCE), reference = JSON.parse(refText);
const manifest = JSON.parse(readText(MANIFEST));
let parity;
const getParity = () => (parity ??= runParity(S, reference));

test('reference: generated by R 4.6.0 / metafor 5.2-1 / metadat 1.6-0 over both corpora', () => {
  assert.deepEqual({R: reference.versions.R, metafor: reference.versions.metafor, metadat: reference.versions.metadat}, {R: '4.6.0', metafor: '5.2.1', metadat: '1.6.0'});
  assert.equal(reference.analyses.length, 88 + 142);
  assert.equal(reference.analyses.filter(a => a.source === 'heterogeneity' && a.loo).length, 88);
  assert.equal(new Set(reference.analyses.map(a => a.id)).size, 230);
  const het = JSON.parse(readFileSync(ROOT + 'heterogeneity/validate/corpus/corpus.json', 'utf8'));
  for (const c of het) assert.equal(reference.analyses.find(a => a.id === c.id).k, c.k, c.id);
  for (const a of reference.analyses) assert.equal(Object.keys(a.combos).length, 27, a.id);
});

test('manifest: rebuilt from the reference it equals the committed file exactly', () => {
  const rebuilt = buildManifest(reference, getParity(), sha256Lf(refText));
  assert.deepEqual(manifest, JSON.parse(JSON.stringify(rebuilt)));
  assert.equal(manifest.referenceSha256, sha256Lf(refText));
  assert.deepEqual(manifest.tolerances.closed, 1e-9); assert.deepEqual(manifest.tolerances.iterative, 1e-6);
});

test('manifest: every listed combination has zero failures on every analysis of each listed measure', () => {
  const p = getParity();
  let listed = 0;
  for (const c of manifest.combos) {
    const run = p[c.method + '/' + c.test];
    for (const m of c.measures) {
      assert.equal(run.byMeasure[m].failed, 0, c.method + '/' + c.test + ' ' + m);
      assert.ok(run.byMeasure[m].analyses > 0);
      listed++;
    }
  }
  assert.ok(listed > 0);
  // Common-effect with Knapp-Hartung is refused by the module but fitted by metafor: never listed.
  for (const t of ['knha', 'adhoc']) assert.ok(!manifest.combos.some(c => c.method === 'FE' && c.test === t));
  // The page configurations the pilots use are listed for generic effects.
  assert.ok(S.allowed(manifest, 'GEN', 'REML', 'z'));
});

test('parity can fail: a perturbed reference value and a perturbed module are both caught', () => {
  const a = structuredClone(reference.analyses.find(x => x.id === 'dat.aloe2013#1'));
  assert.equal(compareCombo(S, a, 'REML', 'z').failures.length, 0);
  a.combos['REML/z'].fit.mu += 2e-6; // |mu| < 1, so REL = absolute difference
  assert.ok(compareCombo(S, a, 'REML', 'z').failures.some(f => f.key === 'mu'));
  const b = structuredClone(reference.analyses.find(x => x.id === 'dat.aloe2013#1'));
  b.combos['DL/z'].fit.tau2 += 2e-9; // closed form: REL 1e-9 must catch 2e-9 (|tau2| < 1)
  assert.ok(compareCombo(S, b, 'DL', 'z').failures.some(f => f.key === 'tau2'));
  b.combos['DL/z'].loo.ciLo[2] += 1e-5;
  assert.ok(compareCombo(S, b, 'DL', 'z').failures.some(f => f.key === 'loo ciLo[2]'));
  const broken = {...S, fit: (y, v, o) => ({...S.fit(y, v, o), se: S.fit(y, v, o).se * 1.001})};
  assert.ok(compareCombo(broken, reference.analyses[0], 'PM', 'knha').failures.length > 0);
  const refusalFlip = structuredClone(reference.analyses[0]); refusalFlip.combos['PM/z'].fit.refused = true;
  assert.ok(compareCombo(S, refusalFlip, 'PM', 'z').failures.some(f => f.key === 'refused'));
});

test('tolerance classes are the pre-registered ones', () => {
  assert.deepEqual({...TOL}, {closed: 1e-9, iterative: 1e-6, derived: 1e-6, I2: 1e-6});
  assert.equal(compareValue('DL', 'tau2', 1 + 5e-10, 1), null);
  assert.notEqual(compareValue('DL', 'tau2', 1 + 2e-9, 1), null);
  assert.equal(compareValue('REML', 'tau2', 1 + 5e-7, 1), null);
  assert.notEqual(compareValue('REML', 'Q', 1 + 2e-9, 1), null);
  assert.equal(compareValue('DL', 'ciLo', 1 + 5e-7, 1), null);
  assert.equal(compareValue('DL', 'I2', 50 + 5e-7, 50), null);
  assert.notEqual(compareValue('DL', 'I2', 50 + 2e-6, 50), null);
  assert.equal(compareValue('FE', 'I2', null, null), null);
  assert.notEqual(compareValue('FE', 'I2', 0, null), null);
});

test('module refusals and input validation', () => {
  assert.equal(S.fit([0.1], [0.01], {method: 'REML', test: 'z'}).refused, true);
  assert.equal(S.fit([0.1, 0.2], [0.01, 0.02], {method: 'FE', test: 'knha'}).refused, true);
  assert.throws(() => S.fit([0.1, 0.2], [0.01, 0], {method: 'REML'}), /positive/);
  assert.throws(() => S.fit([0.1, NaN], [0.01, 0.02], {method: 'REML'}), /finite/);
  assert.throws(() => S.fit([0.1, 0.2], [0.01, 0.02], {method: 'XX'}), /Unknown estimator/);
  assert.throws(() => S.fit([0.1, 0.2], [0.01, 0.02], {method: 'DL', test: 't'}), /Unknown test/);
  const big = Array.from({length: 501}, (_, i) => i / 500), v = big.map(() => 0.05);
  const loo = S.leaveOneOut(big, v, {method: 'DL', test: 'z'});
  assert.equal(loo.refused, true); assert.equal(loo.rows.length, 0);
  assert.equal(S.leaveOneOut(big.slice(0, 500), v.slice(0, 500), {method: 'DL', test: 'z'}).rows.length, 500);
  assert.equal(S.leaveOneOut([1, 2], [1, 1], {method: 'DL'}).refused, true);
  assert.ok(S.fit([.1, .3, .5], [.04, .05, .03], {method: 'DL'}).warnings.some(w => /DerSimonian-Laird/.test(w)));
});

test('manifest gate and base-row identity guard', () => {
  assert.throws(() => S.listed({}, 'OR'), /manifest/);
  const m = {schemaVersion: 1, module: 'sensitivity-v1', combos: [{method: 'REML', test: 'z', measures: ['OR']}]};
  assert.deepEqual(S.listed(m, 'OR'), [{method: 'REML', test: 'z'}]);
  assert.deepEqual(S.listed(m, 'SMD'), []);
  assert.equal(S.allowed(m, 'OR', 'REML', 'knha'), false);
  const yi = [.1, .3, .5, .2, .9, .4, 1.1, .05], vi = [.2, .25, .18, .3, .22, .28, .35, .15].map(s => s * s);
  const row = S.fit(yi, vi, {method: 'REML', test: 'z'});
  // ma-core docstring values (metafor::rma REML): tau2 0.0712971154, mu 0.4053720468, se 0.1258303793.
  assert.ok(Math.abs(row.tau2 - 0.0712971154) < 1e-9 && Math.abs(row.mu - 0.4053720468) < 1e-9 && Math.abs(row.se - 0.1258303793) < 1e-9);
  assert.equal(S.baseRowGuard(row, {mu: row.mu, se: row.se, tau2: row.tau2, k: 8}).pass, true);
  const off = S.baseRowGuard(row, {mu: row.mu + 1e-6, se: row.se});
  assert.equal(off.pass, false); assert.equal(off.diffs[0].key, 'mu');
  assert.equal(S.baseRowGuard(row, {}).pass, false);
  assert.equal(S.baseRowGuard({refused: true}, {mu: 1}).pass, false);
});
