// Run with linkedom available via node_modules or NODE_PATH. No browser claims.
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const {webcrypto,createHash}=require('node:crypto');
const nodeSetTimeout=require('node:timers').setTimeout;
const {parseHTML}=require('linkedom');
const root=path.resolve(__dirname,'../../..'),dir=path.join(root,'correlation-ma/validate');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const write=(p,x)=>fs.writeFileSync(path.join(dir,p),JSON.stringify(x,null,2)+'\n');
const files=()=>Object.fromEntries(['corpus.json','reference.json'].map(n=>['validate/corpus/'+n,Uint8Array.from(fs.readFileSync(path.join(dir,'corpus',n))).buffer]));
function setup(pins) {
  const {window,document}=parseHTML(read('correlation-ma/index.html'));
  window.__almChartExportAuto=false;window.alm={};
  document.readyState='complete';
  Object.defineProperty(document.querySelector('#f-method'),'value',{value:'REML',writable:true});
  // linkedom does not supply browser layout, form readonly defaults or select.disabled.
  for(const id of ['f-data','f-method']) {document.getElementById(id).disabled=false;document.getElementById(id).readOnly=false;}
  window.Element.prototype.getBoundingClientRect=()=>({width:560,height:200});
  window.matchMedia=()=>({matches:false});
  const ctx=vm.createContext({window,document,matchMedia:window.matchMedia,console,URL,Blob,TextEncoder,TextDecoder,ArrayBuffer,Uint8Array,crypto:webcrypto,
    location:{protocol:'http:',origin:'http://localhost',pathname:'/correlation-ma/index.html'},
    setTimeout:(f,n)=>n>100?0:nodeSetTimeout(f,n),clearTimeout,setInterval:()=>0,clearInterval,performance,structuredClone,MutationObserver:window.MutationObserver});
  // Chart scans are explicitly called by replay; no browser animation/layout is simulated.
  window.requestAnimationFrame=()=>0;window.setTimeout=()=>0;
  function run(p){vm.runInContext(read(p),ctx,{filename:p});}
  Object.defineProperty(ctx,'_almLastCorrMA',{get:()=>window._almLastCorrMA});
  run('shared/ma-core.js');run('shared/build-info.js');run('hub/shared/results-export.js');
  vm.runInContext([...document.querySelectorAll('script')].find(s=>s.textContent.includes('var EXAMPLE')).textContent,ctx);
  run('hub/shared/a11y-landmarks.js');run('hub/shared/chart-export-auto.js');
  run('shared/alm-validate.js');ctx.AlmValidate=window.AlmValidate;
  if(pins)window.AlmCorrValidationPins=pins;else run('correlation-ma/validate/pins.js');
  run('correlation-ma/validate/adapter.js');
  return {window,document,ctx,adapter:window.AlmCorrValidationAdapter};
}
function makePins() {
  return {files:['corpus.json','reference.json'].map(n=>{const b=fs.readFileSync(path.join(dir,'corpus',n));return {path:'validate/corpus/'+n,sha256:createHash('sha256').update(b).digest('hex'),bytes:b.length};}),
    checks:0,archived_checks:149379,configurations:72,refused_configurations:8,
    rule:'All eight P17 corpus inputs with at most 100 supplied rows, under REML, PM, DL and FE (32 configurations); all focused P17 probes except the 2,001-row capacity probe (36); four additional empty-field/label probes sharing the two-study R reference.',
    referenceVersions:{R:'4.6.0',metafor:'5.2-1',metadat:'1.6-0'}};
}
async function main() {
  if(process.argv.includes('--build')) {
    const env=setup(makePins());
    const ref=JSON.parse(fs.readFileSync(path.join(dir,'corpus/reference.json'),'utf8'));
    ref.pageText=env.adapter.pageText();write('corpus/reference.json',ref);
    const p=makePins(),e=setup(p),r=await e.adapter.corpus.run(files());
    assert.equal(r.failed.length,0,JSON.stringify(r.failed.slice(0,3)));p.checks=r.checks;
    write('MANIFEST.json',p);
    fs.writeFileSync(path.join(dir,'pins.js'),'// SHA-256 over committed LF bytes. Generated by the Node fixture builder.\nwindow.AlmCorrValidationPins = '+JSON.stringify(p,null,2)+';\n');
    console.log('Built manifest:',r.checks,'checks');return;
  }
  const manifest=JSON.parse(fs.readFileSync(path.join(dir,'MANIFEST.json'),'utf8'));
  const e=setup(),snap=e.window.__almCorrValidationSnapshot(),html=e.document.getElementById('forest-host').innerHTML;
  assert.equal(JSON.stringify(e.window.AlmCorrValidationPins),JSON.stringify(manifest));
  for(const [name,bytes] of Object.entries(files())) assert(!Buffer.from(bytes).includes(13),name+' must use LF bytes');
  const result=await e.adapter.corpus.run(files());
  assert.equal(result.failed.length,0,JSON.stringify(result.failed.slice(0,3)));assert.equal(result.checks,manifest.checks);assert.equal(result.refusals.length,8);
  assert.equal(e.window._almLastCorrMA(),snap.last);assert.equal(e.document.getElementById('forest-host').innerHTML,html);
  assert.equal(e.document.getElementById('f-data').value,snap.data);assert.equal(e.document.getElementById('f-method').value,snap.method);
  console.log(`Replay: ${result.passed}/${result.checks}; ${result.refusals.length} refusals; restored original nodes and results`);
  for(const [name,mutate,q] of [
    ['number',d=>{const c=d.querySelector('#res-body tr td:nth-child(2)');if(c)c.textContent='99';},'display.table'],
    ['label',d=>{const c=d.querySelector('#res-body tr td');if(c)c.textContent='Invented';},'display.table'],
    ['refusal',d=>{if(!d.querySelector('#res-body tr'))d.getElementById('headline').textContent='Results verified';},'refusal.message'],
    ['static text',d=>{d.querySelector('h1').textContent='Other method';},'page_text'],
    ['control',d=>{d.getElementById('f-method').disabled=false;},'controls'],
    ['forest',d=>{const c=d.querySelector('#forest-host circle');if(c)c.setAttribute('cx','999');},'plot.marker.cx'],
    ['numerical result',()=>{const a=globalThis._almLastCorrMA();if(a)a.mu_z+=.1;},'mu_z'],
  ]) {
    const e=setup(),run=e.window.__almCorrValidationRun;e.window.__almCorrValidationRun=()=>{run();mutate(e.document);};
    const r=await e.adapter.corpus.run(files());
    assert(r.failed.some(f=>f.quantity===q),name+' must fail');
    console.log(`Negative ${name}: ${r.failed.length} failed checks (expected)`);
  }
  for(const spec of manifest.files) {
    const f=files();new Uint8Array(f[spec.path])[10]^=1;
    await assert.rejects(()=>setup().adapter.corpus.run(f),/SHA-256 mismatch/);
  }
  console.log('Negative pins: both files refused (expected)');
  {
    const e=setup(),before=e.window.__almCorrValidationSnapshot();
    e.window.__almCorrValidationRun=()=>{throw Error('Injected render failure');};
    await assert.rejects(()=>e.adapter.corpus.run(files()),/Injected render failure/);
    assert.equal(e.document.getElementById('f-data').value,before.data);
    assert.equal(e.document.getElementById('f-method').value,before.method);
    assert.equal(e.document.getElementById('f-data').disabled,false);
    assert.equal(e.window._almLastCorrMA(),before.last);
  }
  console.log('Thrown replay error: original state restored');
  for(const method of ['REML','PM','DL','FE']) {
    const e=setup();e.document.getElementById('f-method').value=method;
    const s=e.adapter.live.currentState(),script=e.adapter.live.buildScript(s);
    assert.equal(s.method,method);assert.equal(s.values.length,12);assert(script.includes("method='"+method+"'"));
    assert(s.values.filter(v=>['display','controls'].includes(v.key)).every(v=>v.value===true));
  }
  console.log('Live payloads: four estimators; R execution deferred');
}
main().catch(e=>{console.error(e);process.exitCode=1;});
