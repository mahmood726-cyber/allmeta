/* powerma/rcheck.js -- the page's R user path (app-local).
 *
 * buildRScript(state) returns a self-contained R script that recomputes, from the inputs the page analysed, every
 * number in the "Required information" table (N per arm, total N and event target for the single-study, I²-adjusted
 * and D²-adjusted rows), prints each next to the value the page displays with the absolute difference, and ends with
 * "MATCH n/n" or "MISMATCH k/n" computed from those comparisons (integers, so exact).
 *
 * The paper-46 validation checks these sizes against closed forms and RTSA 0.2.2 ris(); RTSA is not in the WebR
 * repository, so the script writes the published formulas in base R (arcsine / Cohen h, the pooled-variance normal
 * approximation that RTSA ris() and the TSA program use, and the continuous two-sample formula) and says so.
 *
 * attach() wires "Verify in R" (runs the same script in WebR via the unchanged shared/webr-runner.js and shows R's
 * output verbatim) and "Download R script".
 */
(function (global) {
  "use strict";

  function num(x) {
    if (x === null || x === undefined || (typeof x === "number" && !isFinite(x))) return "NA";
    return String(Number(x).toPrecision(17)).replace(/^(-?)0+(\d)/, "$1$2");
  }
  function vec(a) { return "c(" + a.map(num).join(", ") + ")"; }

  // state: { outcome, method ("arcsine"|"pooled"), alpha, power, ratio, i2Pct, d2Pct, p0, rrr, md, sd,
  //          page: [[nPerArm, totalN, events|null] x 3 rows: single study, I²-adjusted, D²-adjusted] }
  function buildRScript(st) {
    var L = [];
    L.push("# PowerMA required information size: independent R check, generated by allmeta powerma from the inputs");
    L.push("# the page analysed. Run in a fresh R session: Rscript this-file.R. Base R only (no package needed).");
    L.push("# The paper's validation compares these sizes with closed forms and RTSA 0.2.2 ris(); RTSA is not");
    L.push("# available in WebR, so the published formulas are written out below:");
    L.push("#   binary, arcsine (Cohen h):   n = (z_a + z_b)^2 / (2 asin sqrt(p1) - 2 asin sqrt(p0))^2 * (1 + 1/ratio)");
    L.push("#   binary, pooled variance (RTSA ris(), TSA program): n = (z_a + z_b)^2 pbar (1 - pbar) (1 + 1/ratio) / (p0 - p1)^2");
    L.push("#   continuous:                  n = 2 (z_a + z_b)^2 / (MD / SD)^2");
    L.push("#   n is per control arm; total = n (1 + ratio); sizes are rounded UP; adjusted rows = ceiling(row * 1 / (1 - I2 or D2)).");
    L.push("");
    L.push("## Inputs (as analysed by the page)");
    L.push("outcome <- \"" + (st.outcome === "continuous" ? "continuous" : "binary") + "\"");
    L.push("binary_formula <- \"" + (st.method === "pooled" ? "pooled" : "arcsine") + "\"");
    L.push("alpha <- " + num(st.alpha) + "; power <- " + num(st.power) + "; ratio <- " + num(st.ratio));
    L.push("I2 <- " + num(st.i2Pct) + " / 100; D2 <- " + num(st.d2Pct) + " / 100");
    L.push("p0 <- " + num(st.p0) + "; rrr <- " + num(st.rrr) + "      # binary: control risk, relative risk reduction");
    L.push("md <- " + num(st.md) + "; sd <- " + num(st.sd) + "        # continuous: mean difference, SD");
    L.push("");
    L.push("## What the page displayed (rows: single study, I2-adjusted, D2-adjusted; NA = shown as a dash)");
    L.push("page <- rbind(" + st.page.map(vec).join(",\n              ") + ")");
    L.push(R_BODY);
    return L.join("\n") + "\n";
  }

  var R_BODY = [
    "",
    "## Computation",
    "za <- qnorm(1 - alpha / 2); zb <- qnorm(power)",
    "if (outcome == \"binary\") {",
    "  p1 <- p0 * (1 - rrr)",
    "  n <- if (binary_formula == \"pooled\") {",
    "    pbar <- (p0 + ratio * p1) / (1 + ratio)",
    "    (za + zb)^2 * pbar * (1 - pbar) * (1 + 1 / ratio) / (p0 - p1)^2",
    "  } else (za + zb)^2 / (2 * asin(sqrt(p1)) - 2 * asin(sqrt(p0)))^2 * (1 + 1 / ratio)",
    "  events <- floor(n * p0 + n * ratio * p1 + 0.5)   # expected events, rounded half up as displayed",
    "} else {",
    "  n <- 2 * (za + zb)^2 / (md / sd)^2",
    "  events <- NA",
    "}",
    "base <- c(ceiling(n), ceiling(n * (1 + ratio)), if (is.na(events) || events == 0) NA else events)",
    "adj <- function(f) if (f < 1) ceiling(base * (1 / (1 - f))) else rep(NA, 3)",
    "r <- rbind(base, adj(I2), adj(D2))",
    "",
    "## Comparison (integers: exact)",
    "rows <- c(\"single study\", sprintf(\"I2-adjusted (%g%%)\", 100 * I2), sprintf(\"D2-adjusted (%g%%)\", 100 * D2))",
    "cols <- c(\"N per arm\", \"total N\", \"event target\")",
    "n_ok <- 0; n_all <- 0",
    "for (i in 1:3) for (j in 1:3) {",
    "  if (outcome != \"binary\" && j == 3 && is.na(page[i, j]) && is.na(r[i, j])) next   # no event target for continuous",
    "  same <- (is.na(page[i, j]) && is.na(r[i, j])) || (!is.na(page[i, j]) && !is.na(r[i, j]) && page[i, j] == r[i, j])",
    "  d <- if (!is.na(page[i, j]) && !is.na(r[i, j])) abs(page[i, j] - r[i, j]) else if (same) 0 else NA",
    "  cat(sprintf(\"%-24s %-13s page %-8s R %-8s |diff| %-4s %s\\n\", rows[i], cols[j], format(page[i, j]), format(r[i, j]),",
    "              format(d), if (same) \"ok\" else \"MISMATCH\"))",
    "  n_all <- n_all + 1; if (same) n_ok <- n_ok + 1",
    "}",
    "cat(sprintf(\"unrounded n per arm %.6f (z_a %.10f, z_b %.10f)\\n\", n, za, zb))",
    "cat(sprintf(\"%s | base R only\\n\", R.version$version.string))",
    "cat(if (n_ok == n_all) sprintf(\"MATCH %d/%d\\n\", n_ok, n_all) else sprintf(\"MISMATCH %d/%d agree\\n\", n_ok, n_all))",
  ].join("\n");

  function esc(s) { return String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;"); }

  // getState(): re-renders the page from its current inputs and returns the state it displays (or null).
  var STALE = "R result discarded: the analysis on the page changed while R was running, so the verdict R returned (for the earlier analysis) is not shown. Press Verify in R again.";
  // opts.current(): the page's record of its latest analysis (a new object on every run, null after a refusal).
  function attach(opts) {
    var verifyGen = 0;   // a later Verify, or a re-run of the analysis, makes an earlier run's answer stale
    var vb = document.querySelector(opts.verifyBtn), db = document.querySelector(opts.downloadBtn);
    if (db) db.addEventListener("click", function () {
      var st = opts.getState();
      if (!st) { alert("Nothing to check: the inputs do not give a sample size."); return; }
      var blob = new Blob([buildRScript(st)], { type: "text/plain;charset=utf-8" });
      var a = document.createElement("a"); a.href = URL.createObjectURL(blob); a.download = opts.filename;
      document.body.appendChild(a); a.click(); document.body.removeChild(a);
      setTimeout(function () { URL.revokeObjectURL(a.href); }, 1000);
    });
    if (vb) vb.addEventListener("click", function () {
      var st = opts.getState();
      if (!window.AlmWebR || typeof AlmWebR.runR !== "function") { alert("The WebR runner (shared/webr-runner.js) did not load; use Download R script instead."); return; }
      AlmWebR.showModal();
      var status = document.getElementById("alm-webr-status"), out = document.getElementById("alm-webr-output");
      if (!st) { status.textContent = "Nothing to check."; out.textContent = "The inputs do not give a sample size."; return; }
      status.textContent = "Booting WebR (first use downloads about 30 MB)...";
      var my = ++verifyGen, snap = opts.current();
      AlmWebR.runR({ script: buildRScript(st), packages: opts.packages, onStatus: function (s) { if (my === verifyGen) status.textContent = s; } }).then(function (res) {
        // R answered for the analysis it was given; if the page has moved on (the modal does not trap focus, so the
        // inputs behind it stay editable), never show that answer beside the new analysis.
        if (my !== verifyGen) return;   // a newer Verify owns the panel
        if (opts.current() !== snap) { status.textContent = STALE; out.textContent = ""; return; }
        if (!res.ok) {
          var pk = /Package not in pinned repository: (\S+)/.exec(res.error || "");
          status.textContent = "R did not run.";
          out.innerHTML = '<strong style="color:#a02929">' + esc(pk ? "The R package " + pk[1] + " is not available in WebR, so the in-browser check cannot run. Use Download R script and run it in R." : "WebR error: " + res.error) + "</strong>";
          return;
        }
        var line = (/^(MATCH \d+\/\d+|MISMATCH .*)$/m.exec(res.stdout) || [null, "no MATCH line (R output incomplete)"])[1];
        var good = /^MATCH /.test(line);
        status.textContent = "R finished: " + line + ". Versions: R " + res.versions.R + "; webR " + res.versions.webR +
          (opts.packages || []).map(function (p) { return "; " + p + " " + res.versions[p]; }).join("");
        out.innerHTML = '<div style="margin:0 0 0.5rem;padding:0.4rem 0.6rem;border-radius:6px;font-weight:600;' +
          (good ? "background:#e7f6ec;color:#1f7a44" : "background:#fdeaea;color:#a02929") + '">' + esc(line) + "</div>" + esc(res.stdout);
      });
    });
  }

  var api = { buildRScript: buildRScript, attach: attach };
  if (typeof module !== "undefined" && module.exports) module.exports = api;
  global.AlmPowerRCheck = api;
})(typeof window !== "undefined" ? window : globalThis);
