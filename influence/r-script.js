/* Influence v2: build a standalone metafor script that reproduces the page's analysis and checks
 * every displayed number against R. The script embeds the app's values, refits with metafor using the
 * global REML likelihood selection, prints the R output, and ends with
 *   "ALL n/n app values reproduced"   (exit status 0)  or
 *   "FAIL m/n app values differ ..."  (exit status 1).
 * Tolerances (archive rule, normalized |app-R|/max(1,|R|)): REML-dependent 1e-6; Q, Q p-value, df 1e-9;
 * influential flags and k exact.
 */
(function (global) {
  'use strict';
  function num(x) {
    if (x === null || x === undefined) return 'NA';
    if (typeof x === 'boolean') return x ? '1' : '0';
    if (!Number.isFinite(x)) throw new Error('Non-finite app value cannot be exported to R');
    return String(x); // shortest round-trip representation: exact double
  }
  function rstr(s) { return '"' + String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/[\r\n\t]/g, ' ') + '"'; }
  function vec(a, f) { return 'c(' + a.map(f || num).join(', ') + ')'; }

  // state: {rows:[{te,se,label}], full, diag, excluded:[0-based], kept: summary or null, version}
  function build(state) {
    var rows = state.rows, full = state.full, diag = state.diag, ex = state.excluded || [];
    if (!rows || rows.length < 3 || !full || !diag || diag.length !== rows.length) throw new Error('Run the analysis first (at least 3 studies).');
    var L = [];
    var p = function (s) { L.push(s); };
    p('# Influence diagnostics: R reproduction script generated by allmeta influence' + (state.version ? ' ' + state.version : '') + '.');
    p('# Generated ' + new Date().toISOString() + '. Tested with R 4.6.0 and metafor 5.2-1.');
    p('# Run with:  Rscript influence-analysis.R   (needs the metafor package).');
    p('# It refits the REML random-effects model, leave1out(), influence(), baujat() and radial(),');
    p('# then compares every value shown by the app with R and exits with status 1 if any differ.');
    p('suppressMessages(library(metafor))');
    p('dat <- data.frame(study = ' + vec(rows, function (r) { return rstr(r.label); }) + ',');
    p('  yi = ' + vec(rows.map(function (r) { return r.te; })) + ',');
    p('  sei = ' + vec(rows.map(function (r) { return r.se; })) + ')');
    p('dat$vi <- dat$sei^2');
    p('# Select REML independently from the data, never from the embedded app values.');
    p('# Orthogonal residual contrasts remove the intercept; their covariance has');
    p('# eigenvalues lambda+t and squared effects z2. Compare boundary and interior');
    p('# modes using adaptive score/likelihood bounds, not a fixed grid or one root.');
    p('reml_tau <- function(y, v) {');
    p('  k <- length(y)');
    p('  stopifnot(length(v) == k, all(is.finite(y)), all(is.finite(v)), all(v > 0))');
    p('  if (k < 2L) return(0)');
    p('  y <- y - y[which.min(v)]');
    p('  scale <- max(sqrt(max(v)), abs(y)); y <- y/scale; v <- (v/scale)/scale');
    p('  unscale <- function(t) { ans <- t*scale*scale; stopifnot(is.finite(ans)); ans }');
    p('  upper <- sum((y-mean(y))^2)');
    p('  if (upper == 0) return(0)');
    p('  if (k == 2L) return(unscale(max(0, ((y[1]-y[2])^2-sum(v))/2)))');
    p('  if (all(v == v[1])) return(unscale(max(0, upper/(k-1)-v[1])))');
    p('  H <- qr.Q(qr(matrix(1, k, 1)), complete = TRUE)[, -1, drop = FALSE]');
    p('  eig <- eigen(crossprod(H, v*H), symmetric = TRUE)');
    p('  lambda <- eig$values; z2 <- drop(crossprod(eig$vectors, crossprod(H, y)))^2');
    p('  if (any(lambda <= 0)) stop("REML contrast covariance exceeds numerical precision")');
    p('  upper <- sum(z2) # Each score term is negative for t >= upper.');
    p('  evaluations <- 0L; eps <- 64*.Machine$double.eps*(k+1)');
    p('  at <- function(t) {');
    p('    evaluations <<- evaluations + 1L');
    p('    if (evaluations > 100000L) stop("REML global likelihood search did not resolve")');
    p('    d <- lambda+t; A <- sum(z2/d^2); B <- sum(1/d)');
    p('    ans <- list(t=t, ll=-sum(log(d)+z2/d)/2, A=A, B=B, s=(A-B)/2,');
    p('                C=sum(z2/d^3), D=sum(1/d^2))');
    p('    if (any(!is.finite(unlist(ans)))) stop("REML search exceeds numerical precision")');
    p('    ans');
    p('  }');
    p('  boundary <- at(0); best <- boundary');
    p('  take <- function(p) {');
    p('    if (p$ll > best$ll || (best$t == 0 && boundary$s > 0 && p$t > 0 &&');
    p('        p$ll >= best$ll-eps*max(1, abs(best$ll)))) best <<- p');
    p('  }');
    p('  polish <- function(a, b) {');
    p('    for (j in seq_len(200L)) {');
    p('      mid <- a$t+(b$t-a$t)/2');
    p('      if (mid == a$t || mid == b$t) break');
    p('      m <- at(mid); if (m$s > 0) a <- m else b <- m');
    p('    }');
    p('    take(at(a$t+(b$t-a$t)/2))');
    p('  }');
    p('  stack <- list(list(boundary, at(upper)))');
    p('  while (length(stack)) {');
    p('    interval <- stack[[length(stack)]]; stack[[length(stack)]] <- NULL');
    p('    a <- interval[[1]]; b <- interval[[2]]; width <- b$t-a$t');
    p('    # A(t) and B(t) decrease, bounding the score throughout [a,b].');
    p('    sLo <- (b$A-a$B-eps*(b$A+a$B))/2');
    p('    sHi <- (a$A-b$B+eps*(a$A+b$B))/2');
    p('    if (a$t > 0 && a$s == 0) take(a)');
    p('    if (b$s == 0) take(b)');
    p('    if (sLo > 0 || sHi < 0) next');
    p('    if (a$s > 0 && b$s < 0 && !(best$t > 0 && a$t <= best$t && best$t <= b$t)) polish(a, b)');
    p('    # ll\'\' = D/2-C. Strict concavity certifies the bracketed maximum.');
    p('    if (a$D*(1+eps)/2 < b$C*(1-eps)) next');
    p('    # Integrating either score bound limits every possible interior gain.');
    p('    riseA <- width*max(0, sHi); riseB <- width*max(0, -sLo)');
    p('    bound <- min(a$ll+riseA+eps*(abs(a$ll)+riseA), b$ll+riseB+eps*(abs(b$ll)+riseB))');
    p('    if (bound <= best$ll + 1e-11 + eps*max(k, abs(best$ll))) next');
    p('    floor <- min(lambda)');
    p('    mid <- if (b$t+floor > 4*(a$t+floor)) sqrt(a$t+floor)*sqrt(b$t+floor)-floor else a$t+width/2');
    p('    if (mid <= a$t || mid >= b$t) next');
    p('    m <- at(mid); stack <- c(stack, list(list(a, m), list(m, b)))');
    p('  }');
    p('  unscale(best$t)');
    p('}');
    p('# Fix tau2 only after selecting it for THIS subset. This prevents metafor\'s');
    p('# local optimizer/boundary check from replacing the selected mode.');
    p('refit <- function(...) {');
    p('  args <- list(...); keep <- if (is.null(args$subset)) seq_along(args$yi) else args$subset');
    p('  args$tau2 <- reml_tau(args$yi[keep], args$vi[keep])');
    p('  do.call(metafor::rma.uni, args)');
    p('}');
    p('fit <- function(y, v, slab) refit(yi=y, vi=v, slab=slab, method="REML", test="z")');
    p('# The existing code2 hooks bind the subset fitter locally in each diagnostic.');
    p('# They do not mutate the full model or hold its tau2 fixed across deletions.');
    p('code <- "rma.uni <- refit"');
    p('res <- fit(dat$yi, dat$vi, dat$study)');
    p('print(res)');
    p('loo <- leave1out(res, code2 = code)');
    p('print(loo)');
    p('inf <- influence(res, code2 = code)');
    p('print(inf)');
    p('pdf("influence-plots.pdf")');
    p('plot(inf); baujat(res, code2 = code); radial(rma(dat$yi, dat$vi, method = "FE"))');
    p('invisible(dev.off())');
    p('excluded <- ' + (ex.length ? vec(ex.map(function (i) { return i + 1; })) : 'integer(0)') + '  # 1-based rows excluded in the app');
    p('if (length(excluded)) {');
    p('  res_ex <- fit(dat$yi[-excluded], dat$vi[-excluded], dat$study[-excluded])');
    p('  cat("\\nRe-fit excluding:", paste(dat$study[excluded], collapse = "; "), "\\n"); print(res_ex)');
    p('}');
    p('');
    p('# ---- App values (as computed in the browser) -------------------------------------------');
    var app = [], R = [], tol = [];
    function add(name, appValue, rExpr, t) { app.push(appValue); R.push(rExpr); tol.push(t); names.push(name); }
    var names = [];
    var T6 = 1e-6, T9 = 1e-9;
    add('full.mu', full.mu, 'as.numeric(coef(res))', T6);
    add('full.se', full.seMu, 'res$se', T6);
    add('full.ci.lb', full.ciLo, 'res$ci.lb', T6);
    add('full.ci.ub', full.ciHi, 'res$ci.ub', T6);
    add('full.zval', full.z, 'res$zval', T6);
    add('full.pval', full.p, 'res$pval', T6);
    add('full.tau2', full.tau2, 'res$tau2', T6);
    add('full.I2', full.I2, 'res$I2', T6);
    add('full.H2', full.H2, 'res$H2', T6);
    add('full.QE', full.Q, 'res$QE', T9);
    add('full.QEp', full.Qp, 'res$QEp', T9);
    add('full.k', rows.length, 'res$k', 0);
    var per = [
      ['loo.estimate', 'loo_mu', 'loo$estimate', T6], ['loo.se', 'loo_seMu', 'loo$se', T6],
      ['loo.ci.lb', 'loo_ciLo', 'loo$ci.lb', T6], ['loo.ci.ub', 'loo_ciHi', 'loo$ci.ub', T6],
      ['loo.zval', 'loo_z', 'loo$zval', T6], ['loo.pval', 'loo_p', 'loo$pval', T6],
      ['loo.tau2', 'loo_tau2', 'loo$tau2', T6], ['loo.I2', 'loo_I2', 'loo$I2', T6], ['loo.H2', 'loo_H2', 'loo$H2', T6],
      ['loo.Q', 'loo_Q', 'loo$Q', T9], ['loo.Qp', 'loo_Qp', 'loo$Qp', T9],
      ['inf.rstudent', 'resid', 'inf$inf$rstudent', T6], ['inf.dffits', 'dffits', 'inf$inf$dffits', T6],
      ['inf.cook.d', 'cooksD', 'inf$inf$cook.d', T6], ['inf.cov.r', 'covRatio', 'inf$inf$cov.r', T6],
      ['inf.hat', 'hat', 'inf$inf$hat', T6], ['inf.weight', 'weight', 'inf$inf$weight', T6],
      ['inf.dfbetas', 'dfbetas', 'inf$dfbs$intrcpt', T6], ['inf.is.infl', 'influential', 'as.numeric(inf$is.infl)', 0]
    ];
    var perApp = [];
    per.forEach(function (q) { perApp.push([q[0], diag.map(function (d) { return d[q[1]]; }), q[2], q[3]]); });
    var kept = state.kept;
    if (ex.length && kept) {
      [['excl.mu', kept.mu, 'as.numeric(coef(res_ex))', T6], ['excl.se', kept.seMu, 'res_ex$se', T6],
       ['excl.ci.lb', kept.ciLo, 'res_ex$ci.lb', T6], ['excl.ci.ub', kept.ciHi, 'res_ex$ci.ub', T6],
       ['excl.zval', kept.z, 'res_ex$zval', T6], ['excl.pval', kept.p, 'res_ex$pval', T6],
       ['excl.tau2', kept.tau2, 'res_ex$tau2', T6], ['excl.I2', kept.I2, 'res_ex$I2', T6], ['excl.H2', kept.H2, 'res_ex$H2', T6],
       ['excl.QE', kept.Q, 'res_ex$QE', T9], ['excl.QEp', kept.Qp, 'res_ex$QEp', T9], ['excl.k', kept.k, 'res_ex$k', 0]]
        .forEach(function (q) { add(q[0], q[1], q[2], q[3]); });
    }
    p('app <- list(');
    var entries = [];
    names.forEach(function (n, i) { entries.push('  ' + rstr(n) + ' = list(app = ' + num(app[i]) + ', r = quote(' + R[i] + '), tol = ' + tol[i] + ')'); });
    perApp.forEach(function (q) { entries.push('  ' + rstr(q[0]) + ' = list(app = ' + vec(q[1]) + ', r = quote(' + q[2] + '), tol = ' + q[3] + ')'); });
    p(entries.join(',\n'));
    p(')');
    p('# ---- Compare (normalized difference |app-R|/max(1,|R|); NA only matches NA) -------------');
    p('n <- 0; bad <- 0');
    p('for (q in names(app)) {');
    p('  a <- app[[q]]$app; r <- as.numeric(eval(app[[q]]$r)); t <- app[[q]]$tol');
    p('  if (length(a) != length(r)) { cat("FAIL", q, ": length app", length(a), "vs R", length(r), "\\n"); n <- n + max(1, length(a)); bad <- bad + max(1, length(a)); next }');
    p('  d <- ifelse(is.na(a) & is.na(r), 0, abs(a - r) / pmax(1, abs(r)))');
    p('  d[is.na(d)] <- Inf');
    p('  n <- n + length(d); f <- which(d > t); bad <- bad + length(f)');
    p('  for (i in head(f, 5)) cat(sprintf("FAIL %s[%d]: app %.10g, R %.10g, normalized difference %.3g > %g\\n", q, i, a[i], r[i], d[i], t))');
    p('}');
    p('cat(sprintf("metafor %s, %s\\n", packageVersion("metafor"), R.version.string))');
    p('if (bad == 0) {');
    p('  cat(sprintf("ALL %d/%d app values reproduced\\n", n, n))');
    p('} else {');
    p('  cat(sprintf("FAIL %d/%d app values differ beyond tolerance\\n", bad, n)); quit(status = 1)');
    p('}');
    return L.join('\n') + '\n';
  }
  var api = { build: build };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  global.AlmInfluenceR = api;
})(typeof window !== 'undefined' ? window : globalThis);
