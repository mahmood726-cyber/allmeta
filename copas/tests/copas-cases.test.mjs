/* ================================== D. a directional property (MINOR-16) == */

test("stronger assumed selection moves the estimate toward the null and raises N.unpubl", () => {
  // Properties of the model rather than of one fixture, and they hold in BOTH
  // selection directions, so a sign error in `left`, revOrder() or
  // adjustSelection() breaks them where a single numeric comparison would not.
  for (const name of Object.keys(FIX.cases)) {
    const c = FIX.cases[name];
    const TE = nums(c.TE), seTE = nums(c.seTE);
    const fit = CC.copas({
      TE, seTE, TE_random: num(c["TE.random"]), seTE_random: num(c["seTE.random"]),
      tau: num(c.tau), ngrid: num(c.ngrid), sign_rsb: num(c["sign.rsb"]),
      level_ma: num(c["level.ma"]), TE_contour: nums(c["TE.contour"]),
    });
    assert.ok(!fit.refused, `${name}: fit refused: ${fit.refused}`);

    // publprob is reported in rev(order(publprob)) order, i.e. descending:
    // 1 (no selection) first, strongest selection last.
    const pp = nums(fit.publprob);
    assert.ok(pp.length >= 2, `${name}: need at least two points`);
    for (let i = 1; i < pp.length; i++)
      assert.ok(pp[i] <= pp[i - 1] + 1e-12,
        `${name}: publprob must be descending; [${i - 1}]=${pp[i - 1]}, [${i}]=${pp[i]}`);
    assert.ok(Math.abs(pp[0] - 1) < 1e-9,
      `${name}: the first point is the (10, 0) no-selection anchor, publprob 1`);

    // Fewer published studies assumed => more unpublished implied. Monotone
    // in the same order.
    const nu = nums(fit.N_unpubl);
    for (let i = 1; i < nu.length; i++)
      assert.ok(nu[i] >= nu[i - 1] - 1e-9,
        `${name}: N.unpubl must not fall as publprob falls; ` +
        `[${i - 1}]=${nu[i - 1]}, [${i}]=${nu[i]}`);
    assert.ok(nu[nu.length - 1] > nu[0],
      `${name}: N.unpubl must actually rise across the line`);

    // Attenuation toward the null. The unadjusted estimate is the first point
    // (no selection); the strongest-selection point must be no further from 0
    // in the same direction. Checked on the signed quantity, so it is a real
    // directional claim and not |x| bookkeeping: these two cases have
    // opposite-signed effects, which is exactly why both are run.
    const te = nums(fit.TE_slope);
    const sgn = Math.sign(te[0]);
    assert.ok(sgn !== 0, `${name}: degenerate unadjusted estimate`);
    assert.ok(sgn * te[te.length - 1] <= sgn * te[0] + 1e-9,
      `${name}: the strongest-selection estimate (${te[te.length - 1]}) is ` +
      `FURTHER from the null than the no-selection one (${te[0]}); ` +
      "assumed publication bias should attenuate, not amplify");
    assert.ok(Math.abs(te[te.length - 1]) < Math.abs(te[0]),
      `${name}: no attenuation at all across the line`);
  }
});

