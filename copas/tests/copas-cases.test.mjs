  const S = FIX.surfaces[s];
  test(`surface ${s}: base::pretty matches R (1e-9)`, () => {
    close(`${s} pretty.levels`, CC.rPretty(nums(S.z), 10), S["pretty.levels"], TOL_DET);
  });

  test(`surface ${s}: grDevices::contourLines matches R (1e-9)`, () => {
    // These surfaces exist to reach contourLines()'s awkward branches: the
    // four-intersection cell that leaks `xl` (R-QUIRK 1), the all-negative
    // surface that leaves zmax at DBL_MIN (R-QUIRK 2), the nacode branches
    // and the no-crossing case. Each reproduced quirk LOOKS like a bug, so
    // without a test a future contributor fixes it and silently changes
    // every adjusted estimate the app reports.
    const lines = CC.contourLines(nums(S.x), nums(S.y), nums(S.z),
      nums(S["pretty.levels"]));
    const rl = [].concat(S["contour.lines"] || []);
    assert.equal(lines.length, rl.length,
      `${s}: ${lines.length} contour lines vs R's ${rl.length}`);
    for (let i = 0; i < rl.length; i++) {
      close(`${s} line${i}.level`, [lines[i].level], [rl[i].level], TOL_DET);
      close(`${s} line${i}.x`, lines[i].x, rl[i].x, TOL_DET);
      close(`${s} line${i}.y`, lines[i].y, rl[i].y, TOL_DET);
    }
  });
