/* ========================================================== A. the pool === */

for (const dataset of ["hackshaw", "small_k"]) {
  const P = FIX.pools[dataset];
  const TE = nums(P.TE), seTE = nums(P.seTE);
  const vi = seTE.map((s) => s * s);

  test(`${dataset}: AlmMaCore.pool matches metagen's DerSimonian-Laird (1e-12)`, () => {
    // This is the module the page's startValues() actually calls, and the
    // estimate it returns is the first row of the page's summary table.
    // DerSimonian-Laird is a closed form on both sides, so there is no
    // convergence slack to allow for and it is held far tighter than the 1e-6
    // the retired Python test used (measured: 2.8e-17).
    const r = P.DL;
    const f = MC.pool(TE, vi, { method: "DL" });
    close("DL TE.random", [f.mu], [r["TE.random"]], 1e-12);
    close("DL seTE.random", [f.se], [r["seTE.random"]], 1e-12);
    close("DL tau2", [f.tau2], [r.tau2], 1e-12);
    close("DL tau", [Math.sqrt(f.tau2)], [r.tau], 1e-12);
    close("DL Q", [f.Q], [r.Q], 1e-12);
  });

  test(`${dataset}: AlmMaCore.pool matches metagen's REML, to solver tolerance`, () => {
    // REML is the page's SHIPPED default and is iteratively solved on both
    // sides -- shared/ma-core.js and meta::metagen each run their own
    // iteration to their own stopping rule -- so the two cannot agree to
    // machine precision. The bounds below are measured against meta 8.5.0
    // (lanes/rev212/logs/pool-parity.log), not chosen for comfort:
    //
    //   dataset    mu       seTE     tau2     tau
    //   hackshaw   5.4e-7   2.6e-7   6.4e-7   2.2e-6
    //   small_k    2.2e-16  2.8e-17  0        0        (tau2 = 0, a boundary)
    //
    // tau is the loosest only because `close` normalises by max(1, |ref|) and
    // tau ~ 0.15, so these are ABSOLUTE differences and sqrt amplifies:
    // d(tau) = d(tau2) / (2*tau). The displayed estimate (mu) agrees to about
    // seven significant figures, the page prints three decimals, and in
    // copas() this value is only the optimiser's start -- so the residual is
    // recorded rather than chased. It IS a real difference between two REML
    // implementations and is reported as a finding, not a pass.
    const r = P.REML;
    const f = MC.pool(TE, vi, { method: "REML" });
    close("REML TE.random", [f.mu], [r["TE.random"]], TOL_POOL);
    close("REML seTE.random", [f.se], [r["seTE.random"]], TOL_POOL);
    close("REML Q", [f.Q], [r.Q], TOL_POOL);
    close("REML tau2", [f.tau2], [r.tau2], 1e-5);
    close("REML tau", [Math.sqrt(f.tau2)], [r.tau], 1e-5);
    // And pin the size of the residual, so a regression that made it worse
    // by an order of magnitude fails instead of sliding under 1e-5.
    const dTau2 = Math.abs(f.tau2 - num(r.tau2));
    assert.ok(dTau2 <= 1e-6,
      `REML tau2 now differs from metagen by ${dTau2.toExponential(2)}, ` +
      "an order of magnitude worse than the measured 6.4e-7 — ma-core.js's " +
      "REML iteration has changed");
  });

  test(`${dataset}: commonEffect matches metagen's TE.common (1e-6)`, () => {
    // The unadjusted fixed-effect pool. copas() uses it to pool the
    // per-contour-line slopes, and the pre-PR footer claimed it matched
    // metafor to 1e-6 -- a claim with nothing behind it once the old Python
    // test went. TE.common does not depend on method.tau, so both entries
    // carry the same value and either is the reference.
    const want = num(P.REML["TE.common"]);
    close("TE.common", [CC.commonEffect(TE, seTE)], [want], TOL_POOL);
    assert.equal(num(P.DL["TE.common"]), want,
      "TE.common must not depend on method.tau");
  });

  test(`${dataset}: copas()'s DerSimonian-Laird fallback matches metagen (1e-6)`, () => {
    // Exercised by OMITTING TE_random, which is the one thing the metasens
    // fixture never does -- it always supplies it, so this closed-form path
    // had no coverage at all. Only the start values are checked here; whether
    // the fit then succeeds is the other suites' business.
    const r = P.DL;
    const fit = CC.copas({ TE, seTE, ngrid: 10 });
    assert.ok(!fit.refused, `fit refused: ${fit.refused}`);
    close("DL fallback TE.random", [fit.TE_random], [r["TE.random"]], TOL_POOL);
    close("DL fallback seTE.random", [fit.seTE_random], [r["seTE.random"]], TOL_POOL);
    close("DL fallback tau", [fit.tau], [r.tau], TOL_POOL);
  });
}

