/* median-to-mean/r-check.js -- "Verify in R" and "Download R script" for this page.
 *
 * Both buttons use ONE script, generated from the inputs the page last analysed
 * (window.__almM2MInputs, recorded by runCalc) and the full-precision numbers behind
 * the table it displays (window.__almLastM2M). The script recomputes every displayed
 * mean and SD in R and prints each one next to the page's value, the absolute
 * difference and a final MATCH n/n or MISMATCH line.
 *
 * Reference, as in the P24 validation: the published closed forms of Wan 2014, Luo 2018
 * and Shi 2020 written out in base R (R's exact qnorm), plus metaBLUE 1.0.0 (Luo.mean,
 * Wan.std) as a counted package check when it is installed.
 *
 * "Verify in R" runs the same script in the browser with WebR through the unchanged
 * ../shared/webr-runner.js (loaded on first click). metaBLUE is not in WebR's pinned
 * repository, so in the browser its lines are reported NOT CHECKED, never faked.
 */
(function () {
  "use strict";

  // A relative 1e-9 alone is LOOSER than the 3 decimals shown once |value| > 5e5 (a mean of 3e6 would pass an
  // error of 0.002), so the tolerance is capped at half a unit of the displayed 3rd decimal.
  var TOL_NOTE = "|R - page| <= min(5e-4, 1e-9 * max(1, |page|)): never looser than half a unit of the 3 decimals shown";
  // Packages the script can use; the in-page run passes to WebR only those in its pinned repository.
  var OPTIONAL_PACKAGES = ["metaBLUE"];

  function rnum(x) { return (typeof x === "number" && isFinite(x)) ? String(x) : "NA"; }
  function rstr(s) {
    return '"' + String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/[^\x20-\x7e]/g, function (c) {
      return "\\u" + ("000" + c.charCodeAt(0).toString(16)).slice(-4);
    }) + '"';
  }
  function rvec(xs, f) { return "c(" + xs.map(f).join(", ") + ")"; }

  // Comparison helpers, identical in every script this page writes.
  var R_HELPERS = [
    "## ---- comparison helpers ----",
    ".n <- 0L; .ok <- 0L; .nest <- 0L; .skipped <- character(0)",
    "fmtv <- function(x) if (is.na(x)) \"NA\" else sprintf(\"%.10g\", x)",
    "check <- function(label, r, page, est = TRUE) {   # est = FALSE: a count or a refusal flag, not an estimate",
    "  # " + TOL_NOTE,
    "  both_na <- is.na(r) && is.na(page)",
    "  d <- if (both_na) 0 else abs(r - page)",
    "  ok <- both_na || (!is.na(d) && d <= min(5e-4, 1e-9 * max(1, abs(page))))",
    "  .n <<- .n + 1L; if (ok) .ok <<- .ok + 1L",
    "  if (est && !is.na(r) && !is.na(page)) .nest <<- .nest + 1L   # an estimate actually compared",
    "  cat(sprintf(\"%-46s R %-16s page %-16s |diff| %-8s %s\\n\", label, fmtv(r), fmtv(page),",
    "              if (both_na) \"-\" else sprintf(\"%.1e\", d), if (ok) \"ok\" else \"DIFFERS\"))",
    "}",
    "not_checked <- function(label, why) {",
    "  .skipped <<- c(.skipped, label)",
    "  cat(sprintf(\"%-46s NOT CHECKED (%s)\\n\", label, why))",
    "}",
    "finish <- function() {",
    "  extra <- if (length(.skipped)) sprintf(\" (%d more NOT CHECKED: see above)\", length(.skipped)) else \"\"",
    "  if (.ok < .n) cat(sprintf(\"MISMATCH (%d of %d quantities agree)%s\\n\", .ok, .n, extra))",
    "  # agreeing refusals, row counts and dashes are not a check of any number: never call that a MATCH",
    "  else if (.nest == 0L) cat(sprintf(\"NOT CHECKED (no estimate was compared: the page shows none for these inputs)%s\\n\", extra))",
    "  else cat(sprintf(\"MATCH %d/%d%s\\n\", .ok, .n, extra))",
    "}",
  ].join("\n");

  function buildScript() {
    var inp = typeof window.__almM2MInputs === "function" ? window.__almM2MInputs() : null;
    var res = typeof window.__almLastM2M === "function" ? window.__almLastM2M() : null;
    if (!inp || !res) throw new Error("The page has not analysed any input yet.");
    var rows = res.refused ? [] : (res.estimates || []);
    var build = window.AlmBuildInfo ? (window.AlmBuildInfo.version + " " + (window.AlmBuildInfo.shortSha || "")) : "unknown";
    var L = [];
    L.push("## Median -> Mean/SD: R check of the numbers this page displays.");
    L.push("## Generated by the allmeta median-to-mean page (build " + build.trim() + ") from the inputs it last analysed.");
    L.push("## Reference, as in the P24 validation: the published closed forms of Wan et al. 2014 (mean and SD),");
    L.push("## Luo et al. 2018 (mean) and Shi et al. 2020 (SD) written out in base R with R's exact qnorm(),");
    L.push("## and, when installed, the metaBLUE package (Luo.mean, Wan.std) as an independent check.");
    L.push("## Run with:  Rscript median-to-mean-check.R   (base R is enough; metaBLUE 1.0.0 adds two checks)");
    L.push("");
    L.push(R_HELPERS);
    L.push("");
    L.push("## ---- inputs the page analysed (blank fields are NA) ----");
    L.push("inp <- list(scenario = " + rstr(inp.scenario) + ", n = " + rnum(inp.n) + ", a = " + rnum(inp.a) +
      ", q1 = " + rnum(inp.q1) + ", m = " + rnum(inp.m) + ", q3 = " + rnum(inp.q3) + ", b = " + rnum(inp.b) + ")");
    L.push("## ---- the page's results (full precision behind the displayed 3 decimals) ----");
    L.push("page_refused <- " + (res.refused ? "TRUE" : "FALSE"));
    L.push("page <- data.frame(source = " + rvec(rows, function (r) { return rstr(r.source); }) +
      ",\n                   mean = " + rvec(rows, function (r) { return rnum(r.mean); }) +
      ",\n                   sd = " + rvec(rows, function (r) { return rnum(r.sd); }) + ", stringsAsFactors = FALSE)");
    L.push("");
    L.push("## ---- the published estimators (base R) ----");
    L.push("xi_range <- function(n) 2 * qnorm((n - 0.375) / (n + 0.25))     # Wan 2014: expected range / sigma");
    L.push("xi_iqr   <- function(n) 2 * qnorm((0.75 * n - 0.125) / (n + 0.25)) # Wan 2014: expected IQR / sigma");
    L.push("wan <- function(s, n, a, q1, m, q3, b) switch(s,");
    L.push("  C1 = list(mean = (a + 2 * q1 + 2 * m + 2 * q3 + b) / 8, sd = 0.5 * ((b - a) / xi_range(n) + (q3 - q1) / xi_iqr(n))),");
    L.push("  C2 = list(mean = (a + 2 * m + b) / 4, sd = (b - a) / xi_range(n)),");
    L.push("  C3 = list(mean = (q1 + m + q3) / 3, sd = (q3 - q1) / xi_iqr(n)))");
    L.push("luo_mean <- function(s, n, a, q1, m, q3, b) switch(s,               # Luo 2018");
    L.push("  C1 = { w1 <- 2.2 / (2.2 + n^0.75); w2 <- 0.7 - 0.72 / n^0.55; w1 * (a + b) / 2 + w2 * (q1 + q3) / 2 + (1 - w1 - w2) * m },");
    L.push("  C2 = { w <- 4 / (4 + n^0.75); w * (a + b) / 2 + (1 - w) * m },");
    L.push("  C3 = { w <- 0.7 + 0.39 / n; w * (q1 + q3) / 2 + (1 - w) * m })");
    L.push("shi_sd <- function(s, n, a, q1, m, q3, b) switch(s,                 # Shi 2020 (C3 = Wan's SD; none for C2)");
    L.push("  C1 = { th <- 1 / (1 + 0.07 * n^0.6); th * (b - a) / xi_range(n) + (1 - th) * (q3 - q1) / xi_iqr(n) },");
    L.push("  C2 = NULL,");
    L.push("  C3 = (q3 - q1) / xi_iqr(n))");
    L.push("");
    L.push("## ---- recompute and compare ----");
    L.push("cat(sprintf(\"R %s; scenario %s, n = %s\\n\", getRversion(), inp$scenario, fmtv(inp$n)))");
    L.push("valid_n <- is.finite(inp$n) && inp$n >= 2 && inp$n == round(inp$n)  # the page refuses any other n");
    L.push("check(\"refuses the sample size (1 = yes)\", as.numeric(!valid_n), as.numeric(page_refused), est = FALSE)");
    L.push("if (valid_n) with(inp, {");
    L.push("  w <- wan(scenario, n, a, q1, m, q3, b); lm <- luo_mean(scenario, n, a, q1, m, q3, b); ss <- shi_sd(scenario, n, a, q1, m, q3, b)");
    L.push("  r <- data.frame(source = c(\"Wan 2014\", \"Luo 2018 mean + Wan SD\", if (!is.null(ss)) \"Luo 2018 mean + Shi 2020 SD\"),");
    L.push("                  mean = c(w$mean, lm, if (!is.null(ss)) lm), sd = c(w$sd, w$sd, ss), stringsAsFactors = FALSE)");
    L.push("  check(\"number of rows shown\", nrow(r), nrow(page), est = FALSE)");
    L.push("  for (i in seq_len(min(nrow(r), nrow(page)))) {");
    L.push("    if (r$source[i] != page$source[i]) { check(paste(\"row\", i, \"label matches\"), 0, 1, est = FALSE); next }");
    L.push("    check(paste(r$source[i], \"mean\"), r$mean[i], page$mean[i])");
    L.push("    check(paste(r$source[i], \"SD\"), r$sd[i], page$sd[i])");
    L.push("  }");
    L.push("  # metaBLUE 1.0.0, the package the P24 validation cross-checked (Luo.mean, Wan.std).");
    L.push("  X <- switch(scenario, C1 = c(a, q1, m, q3, b), C2 = c(a, m, b), C3 = c(q1, m, q3))");
    L.push("  type <- c(C1 = \"S3\", C2 = \"S1\", C3 = \"S2\")[[scenario]]");
    L.push("  if (!all(is.finite(X)) || nrow(page) < 2) {");
    L.push("    not_checked(\"metaBLUE::Luo.mean\", \"an input the scenario needs is blank or not a number\")");
    L.push("    not_checked(\"metaBLUE::Wan.std\", \"an input the scenario needs is blank or not a number\")");
    L.push("  } else if (requireNamespace(\"metaBLUE\", quietly = TRUE)) {");
    L.push("    check(\"metaBLUE::Luo.mean\", metaBLUE::Luo.mean(X, n, type)$muhat, page$mean[2])");
    L.push("    check(\"metaBLUE::Wan.std\", metaBLUE::Wan.std(X, n, type)$sigmahat, page$sd[1])");
    L.push("  } else {");
    L.push("    not_checked(\"metaBLUE::Luo.mean\", \"package metaBLUE is not installed\")");
    L.push("    not_checked(\"metaBLUE::Wan.std\", \"package metaBLUE is not installed\")");
    L.push("  }");
    L.push("  # Informational only, NOT counted: meta::metamean implements these estimators with its own");
    L.push("  # conventions, so its numbers can differ slightly from the published closed forms above.");
    L.push("  if (requireNamespace(\"meta\", quietly = TRUE) && all(is.finite(X))) {");
    L.push("    mm <- tryCatch(suppressWarnings(meta::metamean(n = n, median = m, q1 = if (scenario != \"C2\") q1, q3 = if (scenario != \"C2\") q3,");
    L.push("            min = if (scenario != \"C3\") a, max = if (scenario != \"C3\") b, method.mean = \"Luo\", method.sd = \"Wan\")), error = function(e) NULL)");
    L.push("    if (!is.null(mm)) cat(sprintf(\"info (not counted): meta %s metamean Luo/Wan mean %s sd %s\\n\",");
    L.push("        packageVersion(\"meta\"), fmtv(mm$mean[1]), fmtv(mm$sd[1])))");
    L.push("  }");
    L.push("})");
    L.push("finish()");
    return L.join("\n") + "\n";
  }
  window.__almM2MRScript = buildScript;

  // ---- UI -----------------------------------------------------------------
  function el(id) { return document.getElementById(id); }
  function setStatus(s) { var e = el("rcheck-status"); if (e) e.textContent = s; }
  function verdictOf(text) {
    var lines = String(text).split(/\r?\n/).filter(function (l) { return /^(MATCH|MISMATCH|NOT CHECKED)\b/.test(l); });
    return lines.length ? lines[lines.length - 1] : null;
  }
  function showVerdict(v) {
    var e = el("rcheck-verdict"); if (!e) return;
    e.textContent = v || "";
    e.className = "note rcheck-verdict" + (v && /^MATCH\b/.test(v) ? " ok" : "");
    e.hidden = !v;
  }
  function download() {
    var txt;
    try { txt = buildScript(); } catch (e) { setStatus(e.message); return; }
    var blob = new Blob([txt], { type: "text/x-r;charset=utf-8" });
    var url = URL.createObjectURL(blob), a = document.createElement("a");
    a.href = url; a.download = "median-to-mean-check.R";
    document.body.appendChild(a); a.click();
    setTimeout(function () { document.body.removeChild(a); URL.revokeObjectURL(url); }, 0);
    setStatus("Downloaded median-to-mean-check.R: run it with Rscript; its last line is MATCH n/n or MISMATCH.");
  }
  function loadRunner() {
    if (window.AlmWebR && typeof window.AlmWebR.runR === "function") return Promise.resolve(window.AlmWebR);
    return new Promise(function (resolve, reject) {
      var s = document.createElement("script");
      s.src = "../shared/webr-runner.js";
      s.onload = function () { window.AlmWebR ? resolve(window.AlmWebR) : reject(new Error("../shared/webr-runner.js loaded but AlmWebR is missing")); };
      s.onerror = function () { reject(new Error("Could not load ../shared/webr-runner.js")); };
      document.head.appendChild(s);
    });
  }
  function webrPackages() {
    return fetch(new URL("../r-shiny/shinylive/webr/repo/manifest.json", location.href).href, { redirect: "error" })
      .then(function (r) { if (!r.ok) throw new Error("WebR package list unavailable (HTTP " + r.status + ")"); return r.json(); })
      .then(function (m) { return (m.packages || []).map(function (p) { return p.package; }); });
  }
  // Identity of what the script was built from: run/render replace these objects on every new analysis.
  function snapshot() {
    return [typeof window.__almM2MInputs === "function" ? window.__almM2MInputs() : null,
      typeof window.__almLastM2M === "function" ? window.__almLastM2M() : null];
  }
  function sameSnapshot(a, b) { return a.length === b.length && a.every(function (x, i) { return x === b[i]; }); }
  var STALE = "R result discarded: the analysis on the page changed while R was running, so the verdict R returned (for the earlier analysis) is not shown. Press Verify in R again.";
  var busy = false;
  function verify() {
    if (busy) return;
    var script, snap = snapshot();
    try { script = buildScript(); } catch (e) { setStatus(e.message); return; }
    busy = true; el("btn-verify-r").disabled = true;
    var out = el("rcheck-out"); out.hidden = false; out.textContent = ""; showVerdict(null);
    setStatus("Loading WebR (first run downloads R; this can take a few minutes)...");
    webrPackages().then(function (have) {
      var missing = OPTIONAL_PACKAGES.filter(function (p) { return have.indexOf(p) < 0; });
      var use = OPTIONAL_PACKAGES.filter(function (p) { return have.indexOf(p) >= 0; });
      return loadRunner().then(function (W) {
        return W.runR({ script: script, packages: use, onStatus: setStatus });
      }).then(function (res) {
        if (!res.ok) throw new Error(res.error || "WebR failed");
        // R answered for the analysis it was given; if the page has moved on, never show that answer beside the new one.
        if (!sameSnapshot(snap, snapshot())) { out.textContent = ""; showVerdict(null); setStatus(STALE); return; }
        out.textContent = res.stdout;
        var v = verdictOf(res.stdout);
        showVerdict(v || "MISMATCH (R printed no verdict line)");
        setStatus((res.versions && res.versions.R || "R") + " in WebR " + (res.versions && res.versions.webR || "") + " ran the same script as the download." +
          (missing.length ? " Not in this site's pinned WebR package repository: " + missing.join(", ") + " (its lines show NOT CHECKED; run the downloaded script in R with " + missing.join(", ") + " installed to check them)." : ""));
      });
    }).catch(function (e) {
      setStatus("Verify in R could not run: " + (e && e.message || e) + ". The downloaded R script remains the check.");
      showVerdict(null);
    }).then(function () { busy = false; el("btn-verify-r").disabled = false; });
  }
  // Called by runCalc() on every new analysis (or refusal): a verdict R already returned is for the
  // previous analysis, so it is removed, never left beside the new table. A run still in progress is
  // handled by the snapshot check in verify() when its answer arrives.
  var CHANGED = "The analysis changed since the last R check, so that R verdict was removed (it described the earlier analysis). Press Verify in R again.";
  window.__almM2MRInvalidate = function () {
    if (busy) return;
    var out = el("rcheck-out"), v = el("rcheck-verdict");
    var shown = (out && !out.hidden && out.textContent) || (v && !v.hidden);
    if (!shown) return;
    if (out) { out.textContent = ""; out.hidden = true; }
    showVerdict(null);
    setStatus(CHANGED);
  };
  function wire() {
    var v = el("btn-verify-r"), d = el("btn-download-r");
    if (v) v.addEventListener("click", verify);
    if (d) d.addEventListener("click", download);
  }
  wire();
})();
