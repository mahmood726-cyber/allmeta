.libPaths(c('../re/Rlib_dta', Sys.getenv('R_LIBS'), .libPaths()))
versions<-vapply(c('metafor','meta','metasens','metadat'),function(p)as.character(packageVersion(p)),'');print(versions);stopifnot(versions[['metafor']]=='5.2.1',versions[['meta']]=='8.5.0',versions[['metasens']]=='1.5.3')
c<-jsonlite::fromJSON('validate/plus/corpus.json',simplifyVector=FALSE)
r<-jsonlite::fromJSON('validate/plus/reference.json',simplifyVector=FALSE)
data('dat.bornmann2007',package='metadat')
i<-which(vapply(c,function(x)x$dataset=='dat.bornmann2007',TRUE));stopifnot(length(i)==1)
d<-dat.bornmann2007[unlist(c[[i]]$source_rows),]
stopifnot(all(d$waward>0),all(d$maward>0),all(d$wtotal>d$waward),all(d$mtotal>d$maward))
m<-meta::metabin(d$waward,d$wtotal,d$maward,d$mtotal,sm='OR',method='Inverse',method.tau='DL',method.tau.ci='')
stopifnot(max(abs(m$TE-unlist(c[[i]]$te)))<1e-12,max(abs(m$seTE-unlist(c[[i]]$se)))<1e-12)
c[[i]]$binary<-list(measure='OR',rows=lapply(seq_len(nrow(d)),function(j)as.list(unname(c(d$waward[j],d$wtotal[j],d$maward[j],d$mtotal[j])))))
p<-meta::metabias(m,method.bias='Peters',k.min=10)
r[[i]]$methods$Peters<-list(status='ok',values=list(statistic=unname(p$statistic),df=unname(p$df),p=p$pval))
jsonlite::write_json(c,'validate/plus/corpus.json',auto_unbox=TRUE,digits=NA,pretty=TRUE,null='null')
jsonlite::write_json(r,'validate/plus/reference.json',auto_unbox=TRUE,digits=NA,pretty=TRUE,null='null')
cat('PETERS OR SOURCE-VERIFIED',c[[i]]$id,'host',Sys.info()[['nodename']],'\n')