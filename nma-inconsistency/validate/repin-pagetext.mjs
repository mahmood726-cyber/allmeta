// Re-derive ONLY the static page-text contract of the pinned replay in real browsers
// (by default Google Chrome and Microsoft Edge; REPIN_CHANNELS overrides), after a deliberate static-text/accessibility edit.
// Every R reference, refusal, display contract, parsed row and the check count are
// left byte-identical; the script refuses if anything else would change.
//   node nma-inconsistency/validate/repin-pagetext.mjs   (from hub/shared/tests, where @playwright/test is installed)
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath, pathToFileURL } from 'node:url';
const { chromium } = createRequire(process.cwd() + '/')('@playwright/test');
const dir = fileURLToPath(new URL('.', import.meta.url));
const refPath = dir + 'corpus/reference.json', manPath = dir + 'MANIFEST.json', adapterPath = dir + 'adapter.js';
const raw = readFileSync(refPath, 'utf8'), ref = JSON.parse(raw);
if (JSON.stringify(ref) + '\n' !== raw) throw Error('reference.json does not round-trip; refusing');
const app = pathToFileURL(dir + '../index.html').href, texts = {};
for (const channel of (process.env.REPIN_CHANNELS || 'chrome,msedge').split(',')) { // two independent Chromium-family browsers
  const browser = await chromium.launch({ channel });
  const page = await browser.newPage();
  await page.goto(app);
  await page.waitForFunction(() => window.AlmIncoValidationAdapter && window.AlmIncoPlus);
  await page.evaluate(() => AlmIncoPlus.whenIdle());
  texts[channel] = { version: browser.version(), pageText: await page.evaluate(() => AlmIncoValidationAdapter.pageText()) };
  // The template must not depend on result state (same rule as build-fixtures.cjs).
  await page.evaluate(() => window.__almIncoLoad('A,B,.1,.1'));
  if (JSON.stringify(await page.evaluate(() => AlmIncoValidationAdapter.pageText())) !== JSON.stringify(texts[channel].pageText)) throw Error('Template changed with state');
  await browser.close();
}
const [a, b] = Object.values(texts);
if (JSON.stringify(a.pageText) !== JSON.stringify(b.pageText)) throw Error('Chromium and Edge page text differ');
const before = JSON.stringify({ ...ref, pageText: null });
ref.pageText = a.pageText;
if (JSON.stringify({ ...ref, pageText: null }) !== before) throw Error('Only pageText may change');
const out = JSON.stringify(ref) + '\n';
writeFileSync(refPath, out);
const sha = createHash('sha256').update(out).digest('hex'), bytes = Buffer.byteLength(out);
const manRaw = readFileSync(manPath, 'utf8'), man = JSON.parse(manRaw);
const nl = manRaw.endsWith('\r\n') ? '\r\n' : '\n'; // working-copy line ending (git normalises to LF)
if (JSON.stringify(man) + nl !== manRaw || !readFileSync(adapterPath, 'utf8').includes('const CONTRACT = ' + JSON.stringify(man) + '; // generated')) throw Error('MANIFEST.json and adapter CONTRACT disagree; refusing');
const f = man.files.find(x => x.path === 'validate/corpus/reference.json'); f.sha256 = sha; f.bytes = bytes; man.pageText = a.pageText;
writeFileSync(manPath, JSON.stringify(man) + nl);
const src = readFileSync(adapterPath, 'utf8');
const next = src.replace(/^const CONTRACT = .*; \/\/ generated by build-fixtures.cjs$/m, () => 'const CONTRACT = ' + JSON.stringify(man) + '; // generated by build-fixtures.cjs');
if (next === src) throw Error('CONTRACT line not found');
writeFileSync(adapterPath, next);
console.log(JSON.stringify({ browsers: Object.fromEntries(Object.entries(texts).map(([k, v]) => [k, v.version])), sha256: sha, bytes }));
