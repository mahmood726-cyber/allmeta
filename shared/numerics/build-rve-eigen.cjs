'use strict';
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const root = path.resolve(__dirname, '../..');
const files = ['libRblas.so', 'libRlapack.so'];
const pinned = [
  'd4e703f3ae2783d2f63464fe49a9db44e4db48adedd042b54a5a2c74b7f67825',
  'aedceeaf3bae382dc242afd9c84f9169c8ebaa8cc8130e0e7e4167be5a2a5244'
];
const payloads = files.map(name => fs.readFileSync(path.join(root, 'r-shiny/shinylive/webr', name)));
const provenance = payloads.map((bytes, i) => {
  const hash = crypto.createHash('sha256').update(bytes).digest('hex');
  if (hash !== pinned[i]) throw new Error(`Revalidate the LAPACK ABI and parity before updating ${files[i]}`);
  return `${files[i]}: ${bytes.length} bytes, SHA256 ${hash}`;
});
const template = fs.readFileSync(path.join(__dirname, 'rve-eigen-runtime.js'), 'utf8');
const code = template.replace('/* EMBED_LAPACK */ null',
  JSON.stringify(payloads.map(bytes => bytes.toString('base64'))));
fs.writeFileSync(path.join(root, 'shared/rve-eigen.js'),
  '/* Generated by shared/numerics/build-rve-eigen.cjs.\n * ' +
  provenance.join('\n * ') + '\n */\n' + code);
console.log(provenance.join('\n'));
