'use strict';
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const root = path.resolve(__dirname, '../..');
const files = ['libRblas.so', 'libRlapack.so'];
const pinned = [
  'd4e703f3ae2783d2f63464fe49a9db44e4db48adedd042b54a5a2c74b7f67825',
  'aedceeaf3bae382dc242afd9c84f9169c8ebaa8cc8130e0e7e4167be5a2a5244'
];
const template = fs.readFileSync(path.join(__dirname, 'rve-eigen-runtime.js'), 'utf8');
const slots = template.match(/var DATA_SLOT = (\d+), TABLE_SLOT = (\d+), DATA_ALIGN_LOG2 = (\d+);/);
if (!slots) throw new Error('Loader slot constants not found in rve-eigen-runtime.js');
const [dataSlot, tableSlot, alignLog2] = slots.slice(1).map(Number);

// dylink.0 (https://github.com/WebAssembly/tool-conventions/blob/main/DynamicLinking.md):
// subsection 1 is MEM_INFO, subsection 2 is NEEDED.
function dylink(bytes) {
  const section = WebAssembly.Module.customSections(new WebAssembly.Module(bytes), 'dylink.0');
  if (section.length !== 1) throw new Error('Expected one dylink.0 section');
  const b = new Uint8Array(section[0]), at = {i: 0}, out = {needed: []};
  const leb = () => { let v = 0, s = 0, x; do { x = b[at.i++]; v += (x & 127) * 2 ** s; s += 7; } while (x & 128); return v; };
  while (at.i < b.length) {
    const type = b[at.i++], end = leb() + at.i;
    if (type === 1) Object.assign(out, {memorySize: leb(), memoryAlign: leb(), tableSize: leb(), tableAlign: leb()});
    if (type === 2) for (let n = leb(); n--;) { const len = leb(); out.needed.push(Buffer.from(b.subarray(at.i, at.i + len)).toString()); at.i += len; }
    at.i = end;
  }
  return out;
}

const payloads = files.map(name => fs.readFileSync(path.join(root, 'r-shiny/shinylive/webr', name)));
const provenance = payloads.map((bytes, i) => {
  const hash = crypto.createHash('sha256').update(bytes).digest('hex');
  if (hash !== pinned[i]) throw new Error(`Revalidate the LAPACK ABI and parity before updating ${files[i]}`);
  const d = dylink(bytes);
  if (!(d.memorySize <= dataSlot && d.memoryAlign <= alignLog2 && d.tableSize <= tableSlot && d.tableAlign === 0))
    throw new Error(`${files[i]} dylink.0 ${JSON.stringify(d)} exceeds the loader slots`);
  if (d.needed.some(n => !files.slice(0, i).includes(n))) throw new Error(`${files[i]} needs ${d.needed}`);
  return `${files[i]}: ${bytes.length} bytes, SHA256 ${hash}; dylink.0 memory ${d.memorySize} ` +
    `(align 2^${d.memoryAlign}) <= ${dataSlot}, table ${d.tableSize} <= ${tableSlot}`;
});

