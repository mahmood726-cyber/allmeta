// Smoke-load the generated bundle: links both modules against the import
// allowlist and runs one symmetric and one nonsymmetric solve.
delete require.cache[require.resolve(out)];
const eigen = require(out);
const s = eigen([[2, 1], [1, 2]]), g = eigen([[2, 1], [0, 3]]);
if (s.values.join() !== '3,1' || g.values.join() !== '3,2') throw new Error('Generated eigen bundle smoke test failed');
