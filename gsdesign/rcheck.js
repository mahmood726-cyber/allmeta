/* gsdesign/rcheck.js — "Download R script" and "Verify in R (WebR)".
 *
 * One R script, generated from the design of the LAST "Compute boundaries"
 * shown on the page (window._almLastGSD, set by run() in index.html), refits it
 * with gsDesign::gsDesign and prints every displayed boundary quantity next to the
 * page's value with |difference|, then an honest `MATCH n/n` or `MISMATCH m/n`
 * line. Tolerance per quantity = half a unit of the page's displayed precision.
 *
 * R reference (as in the P27 validation): gsDesign 3.11.0. gsDesign is NOT in the
 * pinned same-origin WebR repository, so "Verify in R" says so plainly and checks
 * nothing in the browser; the downloaded script is the check (desktop R with
 * gsDesign installed). The Monte Carlo "Adaptive simulation" section is not part
 * of this check: R and the page use different random-number generators, so the
 * simulated draws cannot coincide. WebR is the unchanged shared/webr-runner.js.
 */
(function (global) {
  "use strict";
  function rnum(x) { return (typeof x === "number" && Number.isFinite(x)) ? String(x) : "NA"; }
  function rstr(x) { return JSON.stringify(String(x)); }
  function tolFixed(d) { return 0.5 * Math.pow(10, -d); }
  // fmtP in index.html: p < 1e-4 -> toExponential(2) (3 significant digits), else toFixed(4)
  function tolP(p) { return p < 1e-4 ? 0.5 * Math.pow(10, Math.floor(Math.log10(p)) - 2) : tolFixed(4); }
  var SF = { obf: "sfLDOF", pocock: "sfLDPocock", landemets: "sfPower", hsd: "sfHSD" };

  function buildScript(G) {
    if (!G || !G.rows || !G.rows.length) throw new Error("Compute the boundaries first (the page shows no design to check).");
    var o = G.opts, d = G.rows.design, rows = G.rows, two = !!o.twoSided, tt = d.testType;
    if (!SF[o.spend]) throw new Error("Unknown spending function: " + o.spend);
    var fut = tt === 3 || tt === 4;
    if (fut && !SF[o.futSpend]) throw new Error("Unknown futility spending function: " + o.futSpend);
    var page = [
      ["inflation", d.inflation, tolFixed(4)],
      ["en_H0_pct", 100 * d.en[0] / d.nFix, tolFixed(1)],
      ["en_H1_pct", 100 * d.en[1] / d.nFix, tolFixed(1)],
      ["power", rows.reduce(function (s, r) { return s + r.probEffH1; }, 0), tolFixed(4)]
    ];
    rows.forEach(function (r) {
      var k = r.look;
      page.push(["info_frac_" + k, r.infoFrac, tolFixed(3)]);
      page.push(["z_eff_" + k, r.z_eff, tolFixed(4)]);
      page.push(["nominal_p_" + k, r.nomP_eff, tolP(r.nomP_eff)]);
      page.push(["cum_alpha_" + k, r.cumAlpha, tolFixed(5)]);
      if (fut) page.push(["z_fut_" + k, r.z_fut, tolFixed(4)]);
      page.push(["p_eff_H1_" + k, r.probEffH1, tolFixed(4)]);
    });
    var L = [];
    L.push("# Group-sequential design: R check of the allmeta gsdesign page (boundaries section)");
    L.push("# Generated by allmeta gsdesign from the design shown on the page; refitted with gsDesign::gsDesign");
    L.push("# (P27 validated against gsDesign 3.11.0). The adaptive Monte Carlo simulation is not checked here:");
    L.push("# R and the page use different random-number generators, so the simulated draws cannot coincide.");
    L.push("# Tolerance: half a unit of the page's displayed precision. Run: Rscript gsdesign-check.R");
    L.push("");
    L.push("k <- " + d.k + "; test.type <- " + tt + "   # 1 one-sided; 2 two-sided symmetric; 3 binding / 4 non-binding futility");
    L.push("alpha_entered <- " + rnum(o.alpha) + (two ? "   # total two-sided alpha as entered; gsDesign takes the one-sided half" : "   # one-sided alpha"));
    L.push("alpha <- " + (two ? "alpha_entered / 2" : "alpha_entered"));
    L.push("beta <- " + rnum(o.beta) + "   # 1 - power");
    L.push("timing <- c(" + d.timing.map(rnum).join(", ") + ")   # information fractions used by the page");
    L.push("sfu <- \"" + SF[o.spend] + "\"; sfupar <- " + rnum(o.param) + "   # efficacy spending (" + o.spend + ")");
    L.push("sfl <- \"" + (fut ? SF[o.futSpend] : SF[o.spend]) + "\"; sflpar <- " + rnum(fut ? o.futParam : o.param) + (fut ? "   # futility beta-spending (" + o.futSpend + ")" : "   # unused for test.type 1/2"));
    L.push("");
    L.push("# Values the page displayed (full precision), and display tolerances");
    L.push("page <- c(" + page.map(function (q) { return q[0] + " = " + rnum(q[1]); }).join(",\n          ") + ")");
    L.push("tol  <- c(" + page.map(function (q) { return q[0] + " = " + String(q[2]); }).join(", ") + ")");
    L.push("");
    L.push("have_gs <- suppressWarnings(requireNamespace(\"gsDesign\", quietly = TRUE))");
    L.push("if (!have_gs) {");
    L.push("  cat(\"NOT CHECKED: package gsDesign is not installed in this R; install.packages(\\\"gsDesign\\\") and rerun.\\n\")");
    L.push("  cat(R.version.string, \"; gsDesign not installed\\n\", sep = \"\")");
    L.push("  cat(sprintf(\"NOT CHECKED 0/%d (package gsDesign not available)\\n\", length(page)))");
    L.push("} else {");
    L.push("  sf <- function(nm) getExportedValue(\"gsDesign\", nm)");
    L.push("  args <- list(k = k, test.type = test.type, alpha = alpha, beta = beta, timing = timing, sfu = sf(sfu), sfupar = sfupar)");
    L.push("  if (test.type %in% c(3, 4)) args <- c(args, list(sfl = sf(sfl), sflpar = sflpar))");
    L.push("  x <- do.call(gsDesign::gsDesign, args)");
    L.push("  two <- test.type == 2");
    L.push("  r <- c(inflation = max(x$n.I), en_H0_pct = 100 * x$en[1], en_H1_pct = 100 * x$en[2],   # n.fix = 1: relative to a fixed design");
    L.push("         power = sum(x$upper$prob[, 2]))");
    L.push("  cum <- cumsum(x$upper$spend) * (if (two) 2 else 1)");
    L.push("  for (i in seq_len(k)) {");
    L.push("    r[paste0(\"info_frac_\", i)] <- x$timing[i]");
    L.push("    r[paste0(\"z_eff_\", i)] <- x$upper$bound[i]");
    L.push("    r[paste0(\"nominal_p_\", i)] <- (if (two) 2 else 1) * pnorm(-x$upper$bound[i])");
    L.push("    r[paste0(\"cum_alpha_\", i)] <- cum[i]");
    L.push("    if (test.type %in% c(3, 4)) r[paste0(\"z_fut_\", i)] <- x$lower$bound[i]");
    L.push("    r[paste0(\"p_eff_H1_\", i)] <- x$upper$prob[i, 2]");
    L.push("  }");
    L.push("  ok <- logical(0)");
    L.push("  cat(sprintf(\"%-14s %20s %20s %10s  %s\\n\", \"quantity\", \"page\", \"R\", \"|diff|\", \"\"))");
    L.push("  for (q in names(page)) {");
    L.push("    a <- page[[q]]; b <- if (q %in% names(r)) r[[q]] else NA");
    L.push("    good <- if (is.na(a) || is.na(b)) (is.na(a) && is.na(b)) else abs(a - b) <= tol[[q]]");
    L.push("    ok[q] <- good");
    L.push("    cat(sprintf(\"%-14s %20.12g %20.12g %10.3g  %s\\n\", q, a, b, if (is.na(a) || is.na(b)) NA else abs(a - b), if (good) \"ok\" else \"DIFFERS\"))");
    L.push("  }");
    L.push("  cat(R.version.string, \"; gsDesign \", as.character(packageVersion(\"gsDesign\")), \"\\n\", sep = \"\")");
    L.push("  n <- length(ok); m <- sum(ok)");
    L.push("  cat(if (m == n && n > 0) sprintf(\"MATCH %d/%d\", m, n) else sprintf(\"MISMATCH %d/%d\", m, n), \"\\n\", sep = \"\")");
    L.push("}");
    return L.join("\n") + "\n";
  }

  function current() { return global._almLastGSD || null; }

  function download() {
    var txt = buildScript(current());
    var blob = new Blob([txt], { type: "text/x-r;charset=utf-8" });
    var url = URL.createObjectURL(blob), a = document.createElement("a");
    a.href = url; a.download = "gsdesign-check.R";
    document.body.appendChild(a); a.click();
    setTimeout(function () { document.body.removeChild(a); URL.revokeObjectURL(url); }, 0);
    return txt;
  }

  async function verify() {
    var out = document.getElementById("rcheck-out"), st = document.getElementById("rcheck-status");
    var btn = document.getElementById("btn-rverify");
    var set = function (t) { if (st) st.textContent = t; };
    var script;
    try { script = buildScript(current()); } catch (e) { set(e.message); return; }
    if (!global.AlmWebR || typeof global.AlmWebR.runR !== "function") { set("WebR runner (../shared/webr-runner.js) did not load; use Download R script."); return; }
    if (btn) btn.disabled = true;
    out.textContent = "";
    set("Starting WebR (first run downloads R, about a minute)... Note: package gsDesign is NOT in the pinned WebR repository, so nothing can be checked in the browser; use Download R script and run it in desktop R with gsDesign installed.");
    var res = await global.AlmWebR.runR({ script: script, packages: [], onStatus: function (t) { set(t); } });
    if (btn) btn.disabled = false;
    if (!res.ok) { set("WebR failed: " + res.error); return; }
    out.textContent = res.stdout;
    var last = (res.stdout.match(/^(MATCH|MISMATCH|NOT CHECKED \d).*$/m) || ["(no MATCH line in R output)"])[0];
    set("R finished (" + res.versions.R + ", webR " + res.versions.webR + "): " + last);
  }

  global.GSDesignRCheck = { buildScript: buildScript, download: download, verify: verify };
  // Loaded at the end of <body>, so the controls already exist: bind directly.
  if (typeof document !== "undefined" && typeof document.getElementById === "function") {
    var d = document.getElementById("btn-rscript"), v = document.getElementById("btn-rverify");
    if (d) d.addEventListener("click", function () {
      try { download(); } catch (e) { var st = document.getElementById("rcheck-status"); if (st) st.textContent = e.message; }
    });
    if (v) v.addEventListener("click", verify);
  }
})(typeof window !== "undefined" ? window : globalThis);
