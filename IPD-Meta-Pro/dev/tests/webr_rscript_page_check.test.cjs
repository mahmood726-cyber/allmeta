'use strict';
// Requirement: the R script the WebR panel offers (Copy R Script / Download R script / the report)
// must let a user check the page in fresh R without reading numbers by eye. For every quantity the
// panel compares it prints the page's value, R's value, |diff| and the panel's own tolerance, and a
// final line computed in R: "MATCH n/n" or "MISMATCH". Before this, the script printed only R's
// model output (no page value, no difference, no verdict).
// Checked here, on the page's own examples (binary, then continuous = the user changes the data):
//   1. the script embeds the CURRENT analysis' values (not the previous dataset's);
//   2. it runs in fresh Rscript and prints MATCH n/n, with every NOT CHECKED row excluded from n;
//   3. a planted defect (one page value perturbed by 0.01) makes it print MISMATCH, naming the row.
//   node dev/tests/webr_rscript_page_check.test.cjs [path/to/ipd-meta-pro.html]
// Needs system Chrome + playwright-core (PLAYWRIGHT_CORE=<dir>/playwright-core) and Rscript with
// metafor (RSCRIPT=<path>). Without them it prints SKIPPED and exits 2: a check that did not run is
// not a pass.
const fs = require('node:fs'), path = require('node:path'), http = require('node:http'), os = require('node:os');
const { spawnSync } = require('node:child_process');
const pageFile = path.resolve(process.argv[2] || path.join(__dirname, '..', '..', 'ipd-meta-pro.html'));
const CHROME = process.env.CHROME || 'C:/Program Files/Google/Chrome/Application/chrome.exe';
const RSCRIPT = process.env.RSCRIPT || 'Rscript';
let chromium = null;
try { chromium = require(process.env.PLAYWRIGHT_CORE || 'playwright-core').chromium; } catch (e) { /* below */ }
if (!chromium || !fs.existsSync(CHROME)) { console.log('SKIPPED: needs system Chrome and playwright-core'); process.exit(2); }
const rProbe = spawnSync(RSCRIPT, ['--vanilla', '-e', 'cat(requireNamespace("metafor", quietly=TRUE))'], { encoding: 'utf8' });
if (rProbe.status !== 0 || !/TRUE/.test(rProbe.stdout || '')) { console.log('SKIPPED: needs Rscript with metafor (RSCRIPT=<path>)'); process.exit(2); }

let failed = 0;
function check(name, ok, detail) { console.log((ok ? 'PASS ' : 'FAIL ') + name + (detail ? '  [' + detail + ']' : '')); if (!ok) failed++; }
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'ipd-rcheck-'));
function runR(script, tag) {
  const f = path.join(tmp, tag + '.R');
  fs.writeFileSync(f, script, 'utf8');
  const r = spawnSync(RSCRIPT, ['--vanilla', f], { encoding: 'utf8', timeout: 300000 });
  fs.writeFileSync(path.join(tmp, tag + '.out'), (r.stdout || '') + '\n--stderr--\n' + (r.stderr || ''));
  const out = r.stdout || '';
  const lines = out.trim().split(/\r?\n/);
  return { status: r.status, out, last: lines[lines.length - 1] || '', file: f };
}
// The page's own JavaScript-literal spelling of a double, as embedded in the script.
const lit = (x) => String(x);

(async () => {
  const dir = path.dirname(pageFile);
  const server = http.createServer((req, res) => {
    const f = path.join(dir, decodeURIComponent(new URL(req.url, 'http://x').pathname));
    if (!f.startsWith(dir) || !fs.existsSync(f) || fs.statSync(f).isDirectory()) { res.writeHead(404); return res.end(); }
    res.writeHead(200, { 'content-type': f.endsWith('.html') ? 'text/html' : f.endsWith('.js') ? 'text/javascript' : 'application/octet-stream' });
    fs.createReadStream(f).pipe(res);
  });
  const PORT = +(process.env.RPATH_PORT || 18436);
  await new Promise((r, j) => { server.once('error', j); server.listen(PORT, '127.0.0.1', r); });
  const browser = await chromium.launch({ executablePath: CHROME, headless: true });
  try {
    const page = await browser.newPage();
    page.on('dialog', (d) => d.dismiss());
    // No WebR is needed or allowed here: the script is generated by the page and run in desktop R.
    await page.route('https://webr.r-wasm.org/**', (route) => route.abort());
    await page.goto('http://127.0.0.1:' + PORT + '/' + path.basename(pageFile), { waitUntil: 'load' });
    await page.waitForFunction(() => typeof window.loadExampleData === 'function' && typeof window.generateRScript === 'function'
      && typeof window.downloadRScript === 'function', null, { timeout: 60000 });

    let prev = null;
    for (const ex of ['binary', 'continuous']) {
      await page.evaluate((e) => { window.__prevPooled = (typeof APP !== 'undefined' && APP.results && APP.results.pooled) ? APP.results.pooled.effect : null; window.loadExampleData(e); }, ex);
      await page.waitForTimeout(3000);
      await page.evaluate(() => window.runAnalysis());
      await page.waitForFunction(() => typeof APP !== 'undefined' && APP.results && APP.results.pooled && APP.results.pooled.effect !== window.__prevPooled, null, { timeout: 120000 });
      const P = await page.evaluate(() => { const p = APP.results.pooled; return { effect: p.effect, se: p.se, Q: p.Q, lower: p.lower, upper: p.upper, k: APP.results.studies.length }; });
      const script = await page.evaluate(() => window.generateRScript());
      // 1. the current analysis' values are embedded in the primary-MA check, in full precision
      const prim = (script.split('(cur_primary)')[1] || '').split('.ipd_scenario')[1] || '';
      check(ex + ': script embeds the page pooled estimate ' + lit(P.effect), prim.includes('`pooled` = ' + lit(P.effect)), prim.slice(0, 160));
      check(ex + ': script embeds the page SE ' + lit(P.se) + ' and Q ' + lit(P.Q), prim.includes('`se` = ' + lit(P.se)) && prim.includes('`Q` = ' + lit(P.Q)));
      if (prev) check(ex + ': the previous dataset\'s pooled value (' + lit(prev.effect) + ') is gone', !script.includes(lit(prev.effect)));
      check(ex + ': the downloaded file is the same script', await page.evaluate(() => new Promise((res) => {
        const orig = URL.createObjectURL; let got = null;
        URL.createObjectURL = (b) => { got = b; return orig.call(URL, b); };
        try { window.downloadRScript(); } finally { URL.createObjectURL = orig; }
        if (!got) return res(false);
        got.text().then((t) => res(t.replace(/^# Generated: .*$/m, '') === window.generateRScript().replace(/^# Generated: .*$/m, '')));
      })));
      // 2. fresh Rscript: MATCH n/n, NOT CHECKED rows excluded from n
      const r = runR(script, ex);
      const m = /^MATCH (\d+)\/(\d+)$/.exec(r.last);
      const nMatch = (r.out.match(/^\[MATCH\]/gm) || []).length;
      const nNc = (r.out.match(/^\[NOT CHECKED\]/gm) || []).length;
      check(ex + ': Rscript exits 0', r.status === 0, 'rc ' + r.status + ' ' + r.file);
      check(ex + ': final line is MATCH n/n', !!m && m[1] === m[2] && +m[1] > 0, r.last);
      check(ex + ': n equals the [MATCH] rows printed (' + nMatch + '), NOT CHECKED rows (' + nNc + ') not counted', !!m && +m[1] === nMatch);
      check(ex + ': primary-MA pooled, se, CI, tau2, I2 and Q are each compared and MATCH',
        ['pooled', 'se', 'ci_lower', 'ci_upper', 'tau2', 'i2', 'Q'].every((k) => new RegExp('^\\[MATCH\\] +Current Analysis - Primary MA :: ' + k + ' \\|', 'm').test(r.out)));
      check(ex + ': leave-one-out count (no R value) is NOT CHECKED with a reason, not MATCH',
        /^\[NOT CHECKED\] Current Analysis - Leave-One-Out :: loo_count \|.*R gives no value/m.test(r.out));
      console.log('    ' + ex + ' Rscript: ' + r.last + '  (' + nNc + ' NOT CHECKED)');
      prev = P;
    }

    // 3. planted defect: the page's SE off by 0.01 (tolerance 0.001) -> MISMATCH, naming the row
    const planted = await page.evaluate(() => { APP.results.pooled.se += 0.01; const s = window.generateRScript(); APP.results.pooled.se -= 0.01; return s; });
    const r = runR(planted, 'planted');
    check('planted defect: Rscript exits 0 and the final line is MISMATCH', r.status === 0 && /^MISMATCH\b/.test(r.last), r.last);
    check('planted defect: the perturbed row is the one flagged', /^\[MISMATCH\] +Current Analysis - Primary MA :: se \|/m.test(r.out));
    console.log('    planted Rscript: ' + r.last);
  } catch (e) { check('ran', false, e.stack || e); }
  finally { await browser.close(); server.close(); }
  console.log('outputs in ' + tmp);
  if (failed) { console.log(failed + ' FAILED'); process.exit(1); }
  console.log('all passed');
})();
