"""Emit runtime-health.{json,csv,md,html} from per-app records."""

from __future__ import annotations
from pathlib import Path
import csv
import json


STATE_ORDER = ("UNKNOWN", "TIMEOUT", "NEEDS-SERVICE", "CONSOLE-ERRORS", "MISSING-MOUNT", "OK")
STATE_TITLES = {
    "UNKNOWN":        "UNKNOWN — probe crashed (no observations)",
    "TIMEOUT":        "TIMEOUT — page did not reach networkidle",
    "NEEDS-SERVICE":  "NEEDS-SERVICE — UI text indicates a backend dependency",
    "CONSOLE-ERRORS": "CONSOLE-ERRORS — non-empty console.error after noise filter",
    "MISSING-MOUNT":  "MISSING-MOUNT — no primary interactive landmark",
    "OK":             "OK — loaded cleanly with a primary mount",
}


def totals(records: list[dict]) -> dict[str, int]:
    out = {s: 0 for s in STATE_ORDER}
    for r in records:
        out[r["state"]] = out.get(r["state"], 0) + 1
    out["total"] = len(records)
    return out


def render_json(records: list[dict], out_path: Path, *, audit_version: str, now_iso: str) -> None:
    payload = {
        "audit_version": audit_version,
        "generated_at": now_iso,
        "totals": totals(records),
        "apps": {r["key"]: {k: v for k, v in r.items() if k != "key"} for r in records},
    }
    out_path.write_text(json.dumps(payload, indent=2, sort_keys=True, ensure_ascii=False), encoding="utf-8")


_CSV_COLS = ("app", "state", "confidence", "load_ok", "timed_out", "load_time_ms",
             "mount_found", "n_console_errors", "n_ui_matches", "reasons")


def _csv_row(r: dict) -> dict:
    p = r.get("probe", {})
    return {
        "app": r["key"],
        "state": r["state"],
        "confidence": r["confidence"],
        "load_ok": p.get("load_ok"),
        "timed_out": p.get("timed_out"),
        "load_time_ms": p.get("load_time_ms"),
        "mount_found": p.get("mount_found"),
        "n_console_errors": len(p.get("console_errors") or []),
        "n_ui_matches": len(p.get("ui_text_matches") or []),
        "reasons": " | ".join(r.get("reasons", [])),
    }


def render_csv(records: list[dict], out_path: Path) -> None:
    with out_path.open("w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(_CSV_COLS))
        w.writeheader()
        for r in records:
            w.writerow(_csv_row(r))


def render_md(records: list[dict], out_path: Path, *, audit_version: str, now_iso: str) -> None:
    t = totals(records)
    lines = [
        "<!-- sentinel:skip-file — generated by audit/runtime_health.py -->",
        "",
        "# allmeta runtime-health audit",
        "",
        f"Generated: {now_iso} · auditor v{audit_version} · {t['total']} apps",
        "",
        "## Summary",
        "",
    ]
    for s in STATE_ORDER:
        lines.append(f"- {STATE_TITLES[s]}: {t[s]}")
    lines.append("")
    for s in STATE_ORDER:
        bucket = sorted([r for r in records if r["state"] == s], key=lambda x: x["key"].lower())
        if not bucket:
            continue
        lines.append(f"## {STATE_TITLES[s]} ({len(bucket)})")
        lines.append("")
        for r in bucket:
            reasons = " · ".join(r.get("reasons", []))
            lines.append(f"- **{r['key']}** — {reasons}")
        lines.append("")
    out_path.write_text("\n".join(lines), encoding="utf-8")


