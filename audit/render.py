def render_html(records: list[dict], out_path: Path, *, audit_version: str, now_iso: str) -> None:
    data = [
        {
            "key": r["key"],
            "state": r["state"],
            "confidence": r["confidence"],
            "reasons": r.get("reasons", []),
        }
        for r in records
    ]
    blob = json.dumps(data, ensure_ascii=False).replace("</", "<\\/")
    html = _HTML_TEMPLATE.replace("__DATA__", blob)
    header = f"<!-- generated {now_iso} · auditor v{audit_version} -->\n"
    out_path.write_text(header + html, encoding="utf-8")
