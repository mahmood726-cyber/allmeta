/* reverse-bayes/rcheck.js — "Download R script" and "Verify in R (WebR)".
 *
 * One R script, generated from the inputs of the LAST analysis shown on the page
 * (window._almLastRevBayes, set by run() in index.html), recomputes every
 * displayed quantity and prints it next to the page's value with |difference|,
 * then an honest `MATCH n/n` or `MISMATCH m/n` line. Tolerance per quantity =
 * half a unit of the page's displayed precision (toFixed(d) -> 0.5e-d;
 * toPrecision(3) -> half a unit in the 3rd significant digit; verdicts exact).
 *
 * R reference (as in the P26 validation): the closed forms of Matthews (2018)
 * and Held (2019), written out in base R below; when ReplicationSuccess is
 * installed its pIntrinsic() is checked as well. ReplicationSuccess is not in the
 * pinned WebR repository, so in the browser that one extra check is reported as
 * NOT CHECKED. WebR is the unchanged shared/webr-runner.js.
 */
(function (global) {
  "use strict";
  function rnum(x) { return (typeof x === "number" && Number.isFinite(x)) ? String(x) : "NA"; }
  function rstr(x) { return JSON.stringify(String(x)); }
  function tolFixed(d) { return 0.5 * Math.pow(10, -d); }
  function tolPrec3(x) { return (typeof x === "number" && x !== 0 && isFinite(x)) ? 0.5 * Math.pow(10, Math.floor(Math.log10(Math.abs(x))) - 2) : 0; }

  function buildScript(S) {
    if (!S || !S.r) throw new Error("Run the analysis first (the page shows no result to check).");
    var r = S.r, sc = r.sceptical, ex = !!(sc && sc.exists), ratio = S.scale === "ratio";
    var iv = ex ? sc.priorInterval95 : [NaN, NaN];
    var page = [
      ["z", r.z, tolFixed(3)], ["p_obs", r.pObs, tolPrec3(r.pObs)],
      ["significant", r.significant ? 1 : 0, 0],
      ["tau_s", ex ? sc.priorSD : NaN, tolFixed(4)],
      ["tau_s_pct", ex ? sc.priorSDoverEffect * 100 : NaN, tolFixed(0)],
      ["prior95_lo", ex ? (ratio ? Math.exp(iv[0]) : iv[0]) : NaN, ratio ? tolFixed(2) : tolFixed(3)],
      ["prior95_hi", ex ? (ratio ? Math.exp(iv[1]) : iv[1]) : NaN, ratio ? tolFixed(2) : tolFixed(3)],
      ["z_limit", r.intrinsic.zLimit, tolFixed(3)], ["p_limit", r.intrinsic.pLimit, tolPrec3(r.intrinsic.pLimit)],
      ["p_sceptical", r.intrinsic.scepticalP, tolPrec3(r.intrinsic.scepticalP)],
      ["credible", r.intrinsic.credible ? 1 : 0, 0]
    ];
    var L = [];
    L.push("# Reverse-Bayes analysis of credibility: R check of the allmeta reverse-bayes page");
    L.push("# Generated by allmeta reverse-bayes from the inputs of the analysis shown on the page.");
    L.push("# Closed forms (base R): Matthews R, R Soc Open Sci 2018;5:171047 (sceptical/critical prior);");
    L.push("#   Held L, R Soc Open Sci 2019;6:181534 (intrinsic credibility). Optional cross-check:");
    L.push("#   ReplicationSuccess::pIntrinsic (P26 validated against ReplicationSuccess 1.3.3).");
    L.push("# Tolerance: half a unit of the page's displayed precision. Run: Rscript reverse-bayes-check.R");
    L.push("");
    L.push("scale <- " + rstr(S.scale) + "   # \"ratio\": log taken; \"diff\": analysis scale");
    L.push("est <- " + rnum(S.est) + "; lo <- " + rnum(S.lo) + "; hi <- " + rnum(S.hi) + "   # estimate and its 95% interval as entered");
    L.push("alpha <- " + rnum(S.alpha) + "   # two-sided significance level");
    L.push("");
    L.push("# Values the page displayed (full precision), and display tolerances (verdicts: 1 = yes, 0 = no)");
    L.push("page <- c(" + page.map(function (q) { return q[0] + " = " + rnum(q[1]); }).join(",\n          ") + ")");
    L.push("tol  <- c(" + page.map(function (q) { return q[0] + " = " + String(q[2]); }).join(", ") + ")");
    L.push("");
    L.push("z95 <- qnorm(0.975)");
    L.push("theta <- if (scale == \"ratio\") log(est) else est");
    L.push("s <- if (scale == \"ratio\") (log(hi) - log(lo)) / (2 * z95) else (hi - lo) / (2 * z95)   # SE from the 95% interval");
    L.push("za <- qnorm(1 - alpha / 2)");
    L.push("z <- theta / s");
    L.push("r <- c(z = z, p_obs = 2 * pnorm(-abs(z)), significant = as.numeric(abs(z) > za))");
    L.push("if (abs(z) > za) {");
    L.push("  tau_s <- sqrt(za^2 * s^4 / (theta^2 - za^2 * s^2))   # Matthews' critical sceptical prior SD");
    L.push("  half <- z95 * tau_s                                   # the prior's own 95% interval is [-half, half]");
    L.push("  r[\"tau_s\"] <- tau_s; r[\"tau_s_pct\"] <- 100 * tau_s / abs(theta)");
    L.push("  r[\"prior95_lo\"] <- if (scale == \"ratio\") exp(-half) else -half");
    L.push("  r[\"prior95_hi\"] <- if (scale == \"ratio\") exp(half) else half");
    L.push("} else r[c(\"tau_s\", \"tau_s_pct\", \"prior95_lo\", \"prior95_hi\")] <- NA   # no sceptical prior: not significant");
    L.push("r[\"z_limit\"] <- sqrt(2) * za                     # Held's intrinsic-credibility limit");
    L.push("r[\"p_limit\"] <- 2 * pnorm(-sqrt(2) * za)");
    L.push("r[\"p_sceptical\"] <- 2 * pnorm(-abs(z) / sqrt(2))");
    L.push("r[\"credible\"] <- as.numeric(abs(z) >= sqrt(2) * za)");
    L.push("have_rs <- suppressWarnings(requireNamespace(\"ReplicationSuccess\", quietly = TRUE))");
    L.push("if (have_rs) {");
    L.push("  page[\"p_sceptical_RS\"] <- page[[\"p_sceptical\"]]; tol[\"p_sceptical_RS\"] <- tol[[\"p_sceptical\"]]");
    L.push("  r[\"p_sceptical_RS\"] <- ReplicationSuccess::pIntrinsic(p = 2 * pnorm(-abs(z)), type = \"Held\")");
    L.push("}");
    L.push("");
    L.push("ok <- logical(0)");
    L.push("cat(sprintf(\"%-15s %20s %20s %10s  %s\\n\", \"quantity\", \"page\", \"R\", \"|diff|\", \"\"))");
    L.push("for (q in names(page)) {");
    L.push("  a <- page[[q]]; b <- r[[q]]");
    L.push("  good <- if (is.na(a) || is.na(b)) (is.na(a) && is.na(b)) else abs(a - b) <= tol[[q]]");
    L.push("  ok[q] <- good");
    L.push("  cat(sprintf(\"%-15s %20.12g %20.12g %10.3g  %s\\n\", q, a, b, if (is.na(a) || is.na(b)) NA else abs(a - b), if (good) \"ok\" else \"DIFFERS\"))");
    L.push("}");
    L.push("if (!have_rs) cat(\"NOT CHECKED: p_sceptical_RS -- package ReplicationSuccess is not installed in this R (the base-R p_sceptical above is checked)\\n\")");
    L.push("cat(R.version.string, if (have_rs) paste0(\"; ReplicationSuccess \", packageVersion(\"ReplicationSuccess\")) else \"; ReplicationSuccess not installed\", \"\\n\", sep = \"\")");
    L.push("n <- length(ok); m <- sum(ok)");
    L.push("cat(if (m == n && n > 0) sprintf(\"MATCH %d/%d\", m, n) else sprintf(\"MISMATCH %d/%d\", m, n),");
    L.push("    if (!have_rs) \" (ReplicationSuccess cross-check NOT CHECKED: package not available)\" else \"\", \"\\n\", sep = \"\")");
    return L.join("\n") + "\n";
  }

  function current() { return global._almLastRevBayes || null; }

  function download() {
    var txt = buildScript(current());
    var blob = new Blob([txt], { type: "text/x-r;charset=utf-8" });
    var url = URL.createObjectURL(blob), a = document.createElement("a");
    a.href = url; a.download = "reverse-bayes-check.R";
    document.body.appendChild(a); a.click();
    setTimeout(function () { document.body.removeChild(a); URL.revokeObjectURL(url); }, 0);
    return txt;
  }

  var verifyGen = 0, inFlight = 0;
  var STALE = "R result discarded: the analysis on the page changed while R was running, so the verdict R returned (for the earlier analysis) is not shown. Press Verify in R again.";
  async function verify() {
    var out = document.getElementById("rcheck-out"), st = document.getElementById("rcheck-status");
    var btn = document.getElementById("btn-rverify");
    var set = function (t) { if (st) st.textContent = t; };
    var script, snap = current();
    try { script = buildScript(snap); } catch (e) { set(e.message); return; }
    var my = ++verifyGen;   // a later Verify, or a re-run of the analysis, makes this run's answer stale
    if (!global.AlmWebR || typeof global.AlmWebR.runR !== "function") { set("WebR runner (../shared/webr-runner.js) did not load; use Download R script."); return; }
    if (btn) btn.disabled = true;
    out.textContent = "";
    set("Starting WebR (first run downloads R, about a minute)... Note: package ReplicationSuccess is not in the pinned WebR repository; its optional cross-check is reported as NOT CHECKED, the base-R closed forms are checked.");
    var res;
    inFlight++;
    try { res = await global.AlmWebR.runR({ script: script, packages: [], onStatus: function (t) { set(t); } }); }
    finally { inFlight--; }
    if (btn) btn.disabled = false;
    // R answered for the analysis it was given; if the page has moved on, never show that answer beside the new one.
    if (my !== verifyGen || current() !== snap) { out.textContent = ""; set(STALE); return; }
    if (!res.ok) { set("WebR failed: " + res.error); return; }
    out.textContent = res.stdout;
    var last = (res.stdout.match(/^(MATCH|MISMATCH).*$/m) || ["(no MATCH line in R output)"])[0];
    set("R finished (" + res.versions.R + ", webR " + res.versions.webR + "): " + last);
  }

  // Called by the page's run() on every new analysis (or refusal): output R already returned is for the
  // previous analysis, so it is removed, never left beside the new result. A run still in progress is
  // handled by the generation/snapshot check in verify() when its answer arrives.
  var CHANGED = "The analysis changed since the last R check, so that R verdict was removed (it described the earlier analysis). Press Verify in R again.";
  function invalidate() {
    if (inFlight) return;
    var out = document.getElementById("rcheck-out"), st = document.getElementById("rcheck-status");
    if (!out || !out.textContent) return;
    out.textContent = "";
    if (st) st.textContent = CHANGED;
  }

  global.RevBayesRCheck = { buildScript: buildScript, download: download, verify: verify, invalidate: invalidate };
  // Loaded at the end of <body>, so the controls already exist: bind directly.
  if (typeof document !== "undefined" && typeof document.getElementById === "function") {
    var d = document.getElementById("btn-rscript"), v = document.getElementById("btn-rverify");
    if (d) d.addEventListener("click", function () {
      try { download(); } catch (e) { var st = document.getElementById("rcheck-status"); if (st) st.textContent = e.message; }
    });
    if (v) v.addEventListener("click", verify);
  }
})(typeof window !== "undefined" ? window : globalThis);
