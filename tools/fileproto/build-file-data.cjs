// build-file-data.cjs -- write classic-script copies of JSON files that pages fetch().
// A page opened from a local copy (file://) cannot fetch() its own files; a <script src>
// still loads, so these pages read the copy there and keep fetch() over http(s).
// hub/shared/tests/unit/file-data-copies.test.mjs fails if a copy drifts from its JSON.
// Run after editing any of the JSON files below:  node tools/fileproto/build-file-data.cjs
"use strict";
const fs = require("fs"), path = require("path");
const ROOT = path.resolve(__dirname, "..", "..");
const read = (rel) => JSON.parse(fs.readFileSync(path.join(ROOT, rel), "utf8"));
const glossaries = fs.readdirSync(path.join(ROOT, "hub/shared")).filter((f) => /^glossary(\.[a-z]{2})?\.json$/.test(f)).sort();
const TARGETS = [
  // tooltips.js: method-help glossaries, keyed by file name.
  { out: "hub/shared/glossary-data.js", global: "ALM_GLOSSARY_FILES", from: glossaries.map((f) => "hub/shared/" + f),
    data: () => Object.fromEntries(glossaries.map((f) => [f, read("hub/shared/" + f)])) },
  // finder/index.html: the Method Finder decision tree.
  { out: "finder/decision-tree-data.js", global: "ALM_FINDER_TREE", from: ["finder/decision-tree.json"],
    data: () => read("finder/decision-tree.json") },
];
module.exports = { TARGETS, ROOT };
if (require.main === module) {
  for (const t of TARGETS) {
    const text = "// GENERATED by tools/fileproto/build-file-data.cjs from " + t.from.join(", ") + ". Do not edit.\n" +
      "// Read only when the page is opened from a local file (file://), where fetch() is blocked.\n" +
      "window." + t.global + " = " + JSON.stringify(t.data()) + ";\n";
    fs.writeFileSync(path.join(ROOT, t.out), text);
    console.log("wrote " + t.out + " (" + text.length + " chars)");
  }
}
