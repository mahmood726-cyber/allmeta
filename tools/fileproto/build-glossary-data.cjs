// build-glossary-data.cjs -- write hub/shared/glossary-data.js from hub/shared/glossary*.json.
// Pages opened from a local copy (file://) cannot fetch() the JSON; tooltips.js loads this
// classic-script copy instead. hub/shared/tests/unit/glossary-file-fallback.test.mjs fails
// if the copy drifts from the JSON files. Run after editing any glossary JSON.
"use strict";
const fs = require("fs"), path = require("path");
const dir = path.resolve(__dirname, "..", "..", "hub", "shared");
const files = fs.readdirSync(dir).filter((f) => /^glossary(\.[a-z]{2})?\.json$/.test(f)).sort();
const data = {};
for (const f of files) data[f] = JSON.parse(fs.readFileSync(path.join(dir, f), "utf8"));
const out = "// GENERATED by tools/fileproto/build-glossary-data.cjs from " + files.join(", ") + ". Do not edit.\n" +
  "// Used by tooltips.js only when the page is opened from a local file (file://), where fetch() is blocked.\n" +
  "window.ALM_GLOSSARY_FILES = " + JSON.stringify(data) + ";\n";
fs.writeFileSync(path.join(dir, "glossary-data.js"), out);
console.log("wrote hub/shared/glossary-data.js (" + files.length + " files, " + out.length + " chars)");
