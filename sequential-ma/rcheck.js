/* sequential-ma/rcheck.js -- the page's R user path (app-local).
 *
 * buildRScript(state) returns a self-contained R script that recomputes, from the inputs the page analysed, every
 * number the "Per-look decisions" table displays (t, z, alpha spent, alpha boundary, futility boundary, decision) and
 * the overall decision, prints each next to the page's value with the absolute difference, and ends with
 * "MATCH n/n" or "MISMATCH k/n" computed from those comparisons (", NOT CHECKED m" is appended when R cannot solve
 * the futility design for the looks; those quantities are then listed, never counted as agreeing).
 *
 * The R side is independent of the page's JavaScript: spending functions are the published Lan-DeMets forms written
 * in base R, and every group-sequential probability is computed by recursive numerical integration written in
 * base R (its own uniform Simpson grid, not the page's mesh). The paper-46 validation checks the page against
 * RTSA 0.2.2, ldbounds 2.0.2 and an exact recursive-integration reference in R checked against mvtnorm; RTSA and
 * ldbounds are not in the WebR repository, so this script needs no package.
 *
 * attach() wires "Verify in R" (runs the same script in WebR via the unchanged shared/webr-runner.js and shows R's
 * output verbatim) and "Download R script".
 */
(function (global) {
  "use strict";

  function num(x) {
    if (x === Infinity) return "Inf";
    if (x === -Infinity) return "-Inf";
    if (x === null || x === undefined || (typeof x === "number" && !isFinite(x))) return "NA";
    return String(Number(x).toPrecision(17)).replace(/^(-?)0+(\d)/, "$1$2");
  }
  function vec(a) { return "c(" + a.map(num).join(", ") + ")"; }
  function str(s) { return '"' + String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"') + '"'; }

  // state: { rows: parsed input rows (kind "tz" or "ysn"), alpha, family, futility, result: computeBoundary(...) }
  function buildRScript(state) {
    var rows = state.rows, r = state.result, L = [];
    var tz = rows[0].kind === "tz";
    L.push("# Sequential MA with alpha-spending: independent R check, generated by allmeta sequential-ma");
    L.push("# from the inputs the page analysed. Run in a fresh R session: Rscript this-file.R");
    L.push("# Reference: spending functions are the published Lan-DeMets (1983) forms written in base R; every");
    L.push("# group-sequential probability by recursive numerical integration in base R (no package needed).");
    L.push("# The paper's validation compares the page with RTSA 0.2.2, ldbounds 2.0.2 and an exact recursive-");
    L.push("# integration reference checked against mvtnorm; RTSA/ldbounds are not used here (not available in WebR).");
    L.push("");
    L.push("## Inputs (as analysed by the page)");
    L.push("alpha <- " + num(state.alpha) + "        # two-sided");
    L.push("family <- " + str(state.family) + "   # OBF | POCOCK | LINEAR (alpha spending; beta spending uses the same family)");
    L.push("futility <- " + (state.futility ? "TRUE" : "FALSE") + "   # non-binding beta-spending futility (RTSA convention), beta = 0.20");
    L.push("beta <- 0.20");
    if (tz) {
      L.push("# Looks given as information fraction t and cumulative Z");
      L.push("t_in <- " + vec(rows.map(function (x) { return x.t; })));
      L.push("z_in <- " + vec(rows.map(function (x) { return x.z; })));
    } else {
      L.push("# Looks given as cumulative pooled effect, SE and N: t = N / max(N), Z = effect / SE");
      L.push("y_cum <- " + vec(rows.map(function (x) { return x.y_cum; })));
      L.push("se_cum <- " + vec(rows.map(function (x) { return x.se_cum; })));
      L.push("n_cum <- " + vec(rows.map(function (x) { return x.n_cum; })));
      L.push("t_in <- n_cum / max(n_cum); z_in <- y_cum / se_cum");
    }
    L.push("");
    L.push("## What the page displayed (full precision)");
    L.push("page_t <- " + vec(r.looks.map(function (l) { return l.t; })));
    L.push("page_z <- " + vec(r.looks.map(function (l) { return l.z; })));
    L.push("page_spent <- " + vec(r.looks.map(function (l) { return l.spend_alpha; })));
    L.push("page_bound <- " + vec(r.looks.map(function (l) { return l.alpha_boundary; })));
    L.push("page_fut <- " + vec(r.looks.map(function (l) { return l.futility_boundary; })) + "   # NA = no futility boundary shown");
    L.push("page_decision <- c(" + r.looks.map(function (l) { return str(l.decision); }).join(", ") + ")");
    L.push("page_overall <- " + str(r.decision));
    L.push(R_BODY);
    return L.join("\n") + "\n";
  }

  var R_BODY = [
    "",
    "## Computation (independent of the page)",
    "ord <- order(t_in); t <- t_in[ord]; z <- z_in[ord]; K <- length(t)",
    "spendf <- function(fam, a, x) {            # Lan-DeMets spending function of level a at fraction x",
    "  x <- pmin(pmax(x, 0), 1)",
    "  out <- switch(fam, OBF = 2 * pnorm(qnorm(1 - a / 2) / sqrt(x), lower.tail = FALSE),",
    "                POCOCK = a * log(1 + (exp(1) - 1) * x), LINEAR = a * x)",
    "  out[x <= 0] <- 0; out[x >= 1] <- a; out",
    "}",
    "# Exact group-sequential probabilities by recursive numerical integration (Armitage, McPherson & Rowe 1969):",
    "# the density of Z_k on its continuation region is carried from look to look on a uniform grid with Simpson",
    "# weights (step <= 0.02 in the z scale, finer when looks are close). Written in base R for this check.",
    "zgrid <- function(lo, hi, mu, step) {",
    "  a <- max(lo, mu - 9); b <- min(hi, mu + 9)",
    "  if (!(b > a)) return(list(z = numeric(0), w = numeric(0)))",
    "  n <- 2 * ceiling((b - a) / step / 2); if (n > 6000) stop(\"two looks are too close in information for this R check\")",
    "  z <- seq(a, b, length.out = n + 1); h <- (b - a) / n",
    "  w <- rep(c(2, 4), length.out = n + 1); w[1] <- 1; w[n + 1] <- 1",
    "  list(z = z, w = w * h / 3)",
    "}",
    "gstep <- function(Iprev, Ik, Inext) {     # grid step: 0.02, or 1/8 of the transition SD to a neighbouring look",
    "  gap <- Inf; if (!is.na(Inext) && Inext > Ik) gap <- Inext - Ik; if (!is.na(Iprev) && Ik > Iprev) gap <- min(gap, Ik - Iprev)",
    "  min(0.02, sqrt(gap / Ik) / 8)",
    "}",
    "gs_start <- function(I1, theta, lo, hi, step) { mu <- theta * sqrt(I1); g <- zgrid(lo, hi, mu, step); list(z = g$z, w = g$w, h = dnorm(g$z - mu), I = I1) }",
    "gs_cross <- function(s, Ik, cc, theta, upper) {   # P(continued to the previous look, then Z_k > cc (upper) or < cc)",
    "  if (is.infinite(cc)) return(if ((cc > 0) == upper) 0 else sum(s$w * s$h))",
    "  d <- Ik - s$I; x <- (cc * sqrt(Ik) - s$z * sqrt(s$I) - theta * d) / sqrt(d)",
    "  sum(s$w * s$h * pnorm(x, lower.tail = !upper))",
    "}",
    "gs_advance <- function(s, Ik, theta, lo, hi, step) {",
    "  d <- Ik - s$I; sd <- sqrt(d); g <- zgrid(lo, hi, theta * sqrt(Ik), step)",
    "  M <- dnorm(outer(g$z * sqrt(Ik) - theta * d, s$z * sqrt(s$I), \"-\") / sd)",
    "  list(z = g$z, w = g$w, h = as.vector(M %*% (s$w * s$h)) * sqrt(Ik) / sd, I = Ik)",
    "}",
    "# Efficacy: at look k, c_k solves P(|Z_j| < c_j for j < k, Z_k >= c_k) = per-side alpha increment (two-sided)",
    "efficacy <- function(tt, inc) {",
    "  K <- length(tt); b <- rep(Inf, K); s <- NULL",
    "  for (k in 1:K) {",
    "    if (inc[k] > 0) b[k] <- if (k == 1) qnorm(inc[1], lower.tail = FALSE) else",
    "      uniroot(function(cc) gs_cross(s, tt[k], cc, 0, TRUE) - inc[k], c(-10, 40), tol = 1e-12)$root",
    "    if (k < K) {",
    "      if (!any(inc[(k + 1):K] > 0)) break     # no later look spends alpha: later boundaries are Inf",
    "      st <- gstep(if (k > 1) tt[k - 1] else NA, tt[k], tt[k + 1])",
    "      s <- if (k == 1) gs_start(tt[1], 0, -b[1], b[1], st) else gs_advance(s, tt[k], 0, -b[k], b[k], st)",
    "    }",
    "  }",
    "  b",
    "}",
    "cum_side <- spendf(family, alpha, t) / 2   # total spending a(t), half per side (Lan-DeMets 1983)",
    "inc_side <- pmax(0, diff(c(0, cum_side)))",
    "bound <- efficacy(t, inc_side)",
    "spent <- inc_side * 2",
    "# Futility: RTSA 0.2.2 non-binding beta-spending under the design drift theta = z(1-alpha/2) + z(1-beta), on an",
    "# information scale inflated by R so that the final futility and efficacy boundaries meet; looks whose futility",
    "# boundary would be negative spend no beta. The futility region is |Z| < l_k.",
    "beta_bounds <- function(tt, eff, theta, R, rm) {",
    "  Kd <- length(tt); cumb <- ifelse(seq_len(Kd) <= rm, 0, spendf(family, beta, pmin(tt, 1)))",
    "  incb <- diff(c(0, cumb)); I <- tt * R; za <- rep(-Inf, Kd); s <- NULL",
    "  for (k in seq_len(Kd)) {",
    "    if (incb[k] > 0) za[k] <- if (k == 1) theta * sqrt(I[1]) + qnorm(incb[1]) else",
    "      tryCatch(uniroot(function(cc) gs_cross(s, I[k], cc, theta, FALSE) - incb[k], c(-40, 40), tol = 1e-12)$root,",
    "               error = function(e) NA_real_)",
    "    if (is.na(za[k])) return(rep(NA_real_, Kd))   # this beta increment cannot be spent at this R: no design",
    "    if (k < Kd) {",
    "      st <- gstep(if (k > 1) I[k - 1] else NA, I[k], I[k + 1])",
    "      s <- if (k == 1) gs_start(I[1], theta, za[1], eff[1], st) else gs_advance(s, I[k], theta, za[k], eff[k], st)",
    "    }",
    "  }",
    "  za",
    "}",
    "# Inflation R: the first sign change of g at or above R = 0.9 on a 0.02 grid (the page's search), then a root.",
    "# When the design ends past full information (t > 1) the root can lie below 0.9, so if there is none above,",
    "# the grid is searched downwards from 0.9 to 0.02 as well. Grid points where the design cannot be solved are",
    "# skipped; NA means no inflation factor was found.",
    "inflation <- function(tt, eff, theta, rm) {",
    "  g <- function(R) eff[length(tt)] - beta_bounds(tt, eff, theta, R, rm)[length(tt)]",
    "  scan <- function(grid) {",
    "    a <- NA; ga <- NA",
    "    for (bb in grid) {",
    "      gb <- g(bb)",
    "      if (is.na(gb)) { a <- NA; ga <- NA; next }",
    "      if (gb == 0) return(bb)",
    "      if (!is.na(ga) && (ga > 0) != (gb > 0)) return(uniroot(g, sort(c(a, bb)), tol = 1e-12)$root)",
    "      a <- bb; ga <- gb",
    "    }",
    "    NA",
    "  }",
    "  R <- scan(seq(0.9, 10, by = 0.02))",
    "  if (is.na(R)) R <- scan(seq(0.9, 0.02, by = -0.02))",
    "  R",
    "}",
    "fut <- rep(NA_real_, K); fut_checked <- TRUE",
    "if (futility) {",
    "  theta <- qnorm(1 - alpha / 2) + qnorm(1 - beta)",
    "  if (t[K] < 1) {                            # design needs its final analysis at t = 1",
    "    td <- c(t, 1); cd <- spendf(family, alpha, td) / 2; ed <- efficacy(td, pmax(0, diff(c(0, cd))))",
    "  } else {                                   # the design ends at the first look with t >= 1",
    "    kEnd <- which(t >= 1)[1]; td <- t[1:kEnd]; ed <- bound[1:kEnd]",
    "  }",
    "  R <- inflation(td, ed, theta, 0); za <- if (is.na(R)) NA else beta_bounds(td, ed, theta, R, 0)",
    "  rm <- if (is.na(R)) 0 else sum(za < 0)",
    "  if (rm > 0) { R <- inflation(td, ed, theta, rm); if (!is.na(R)) za <- beta_bounds(td, ed, theta, R, rm) }",
    "  if (is.na(R) || anyNA(za)) {",
    "    fut_checked <- FALSE",
    "    cat(\"NOTE: R found no futility design (inflation factor) for these looks, so the futility boundaries and the\\n\",",
    "        \"      decisions that depend on them are NOT CHECKED. Futility was requested; check what the page shows.\\n\")",
    "  } else for (k in seq_len(min(K, length(td)))) if (is.finite(za[k]) && za[k] > 0) fut[k] <- za[k]",
    "}",
    "decision <- character(K); taken <- NA",
    "for (k in 1:K) {",
    "  if (!is.na(taken)) { decision[k] <- \"after-stop\"; next }",
    "  d <- \"continue\"",
    "  if (abs(z[k]) >= bound[k]) d <- \"reject-H0\" else if (!is.na(fut[k]) && abs(z[k]) < fut[k]) d <- \"futility\"",
    "  decision[k] <- d; if (d != \"continue\") taken <- d",
    "}",
    "overall <- if (is.na(taken)) \"continue\" else taken",
    "",
    "## Comparison. Tolerances: t, Z 1e-12 (arithmetic); alpha spent 1e-9 (closed form); boundaries 1e-6",
    "## (the paper's exact-reference tolerance; the page shows 3 decimals); decisions exact.",
    "n_ok <- 0; n_all <- 0; n_nc <- 0",
    "notchk <- function(name, page) { cat(sprintf(\"%-22s page %-20s R %-20s NOT CHECKED\\n\", name, format(page, digits = 10), \"-\")); n_nc <<- n_nc + 1 }",
    "cmp <- function(name, page, r, tol) {",
    "  same <- (is.na(page) && is.na(r)) || (!is.na(page) && !is.na(r) && ((is.infinite(page) && page == r) || (is.finite(page) && is.finite(r) && abs(page - r) <= tol)))",
    "  d <- if (!is.na(page) && !is.na(r) && is.finite(page) && is.finite(r)) abs(page - r) else if (same) 0 else NA",
    "  cat(sprintf(\"%-22s page %-20s R %-20s |diff| %-9s %s\\n\", name, format(page, digits = 10), format(r, digits = 10),",
    "              if (is.na(d)) \"NA\" else format(signif(d, 2)), if (same) \"ok\" else \"MISMATCH\"))",
    "  n_all <<- n_all + 1; if (same) n_ok <<- n_ok + 1",
    "}",
    "cmps <- function(name, page, r) {",
    "  same <- identical(page, r)",
    "  cat(sprintf(\"%-22s page %-20s R %-20s %s\\n\", name, page, r, if (same) \"ok\" else \"MISMATCH\"))",
    "  n_all <<- n_all + 1; if (same) n_ok <<- n_ok + 1",
    "}",
    "if (length(page_t) != K) stop(\"page and R disagree on the number of looks\")",
    "for (k in 1:K) {",
    "  cmp(sprintf(\"look %d t\", k), page_t[k], t[k], 1e-12)",
    "  cmp(sprintf(\"look %d z\", k), page_z[k], z[k], 1e-12)",
    "  cmp(sprintf(\"look %d alpha spent\", k), page_spent[k], spent[k], 1e-9)",
    "  cmp(sprintf(\"look %d boundary\", k), page_bound[k], bound[k], 1e-6)",
    "  if (futility && fut_checked) cmp(sprintf(\"look %d futility\", k), page_fut[k], fut[k], 1e-6)",
    "  if (futility && !fut_checked) notchk(sprintf(\"look %d futility\", k), page_fut[k])",
    "  if (fut_checked) cmps(sprintf(\"look %d decision\", k), page_decision[k], decision[k]) else notchk(sprintf(\"look %d decision\", k), page_decision[k])",
    "}",
    "if (fut_checked) cmps(\"overall decision\", page_overall, overall) else notchk(\"overall decision\", page_overall)",
    "cat(sprintf(\"%s | base R only\\n\", R.version$version.string))",
    "nc <- if (n_nc > 0) sprintf(\", NOT CHECKED %d\", n_nc) else \"\"",
    "cat(if (n_ok == n_all) sprintf(\"MATCH %d/%d%s\\n\", n_ok, n_all, nc) else sprintf(\"MISMATCH %d/%d agree%s\\n\", n_ok, n_all, nc))",
  ].join("\n");

  function esc(s) { return String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;"); }

  // getState(): re-renders the page from its current input and returns the state it displays (or null).
  function attach(opts) {
    var vb = document.querySelector(opts.verifyBtn), db = document.querySelector(opts.downloadBtn);
    if (db) db.addEventListener("click", function () {
      var st = opts.getState();
      if (!st) { alert("No looks to check: enter looks and compute boundaries first."); return; }
      var blob = new Blob([buildRScript(st)], { type: "text/plain;charset=utf-8" });
      var a = document.createElement("a"); a.href = URL.createObjectURL(blob); a.download = opts.filename;
      document.body.appendChild(a); a.click(); document.body.removeChild(a);
      setTimeout(function () { URL.revokeObjectURL(a.href); }, 1000);
    });
    if (vb) vb.addEventListener("click", function () {
      var st = opts.getState();
      if (!window.AlmWebR || typeof AlmWebR.runR !== "function") { alert("The WebR runner (shared/webr-runner.js) did not load; use Download R script instead."); return; }
      AlmWebR.showModal();
      var status = document.getElementById("alm-webr-status"), out = document.getElementById("alm-webr-output");
      if (!st) { status.textContent = "Nothing to check."; out.textContent = "Enter looks and compute boundaries first."; return; }
      status.textContent = "Booting WebR (first use downloads about 30 MB)...";
      AlmWebR.runR({ script: buildRScript(st), packages: opts.packages, onStatus: function (s) { status.textContent = s; } }).then(function (res) {
        if (!res.ok) {
          var pk = /Package not in pinned repository: (\S+)/.exec(res.error || "");
          status.textContent = "R did not run.";
          out.innerHTML = '<strong style="color:#a02929">' + esc(pk ? "The R package " + pk[1] + " is not available in WebR, so the in-browser check cannot run. Use Download R script and run it in R." : "WebR error: " + res.error) + "</strong>";
          return;
        }
        var line = (/^(MATCH \d+\/\d+(?:, NOT CHECKED \d+)?|MISMATCH .*)$/m.exec(res.stdout) || [null, "no MATCH line (R output incomplete)"])[1];
        var good = /^MATCH \d+\/\d+$/.test(line);   // a NOT CHECKED part is never shown as a pass
        status.textContent = "R finished: " + line + ". Versions: R " + res.versions.R + "; webR " + res.versions.webR +
          (opts.packages || []).map(function (p) { return "; " + p + " " + res.versions[p]; }).join("");
        out.innerHTML = '<div style="margin:0 0 0.5rem;padding:0.4rem 0.6rem;border-radius:6px;font-weight:600;' +
          (good ? "background:#e7f6ec;color:#1f7a44" : "background:#fdeaea;color:#a02929") + '">' + esc(line) + "</div>" + esc(res.stdout);
      });
    });
  }

  var api = { buildRScript: buildRScript, attach: attach };
  if (typeof module !== "undefined" && module.exports) module.exports = api;
  global.AlmSeqRCheck = api;
})(typeof window !== "undefined" ? window : globalThis);
