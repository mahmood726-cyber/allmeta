"""R parity for the E-value page beyond the paper-22 scope: non-null ("true")
E-values, SMD with a standard error, linear-regression coefficients and risk
differences, against EValue 4.1.4 (fixtures/evalue-extended-reference.json,
generated by fixtures/evalue-extended-reference.R).

The paper-22 validation reported that the page lacked EValue's evalues.RD,
evalues.OLS and the `true` argument; these tests pin the additions to EValue.
Both the engine (shared/evalue.js) and the page's own compute handler are
exercised. Tolerance: |app - R| / max(1, |R|) <= 1e-9.
"""
import json
import shutil
import subprocess
import tempfile
from pathlib import Path

import pytest

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
NODE = shutil.which("node")
pytestmark = pytest.mark.skipif(NODE is None, reason="node not installed")
REF = json.loads((HERE / "fixtures" / "evalue-extended-reference.json").read_text(encoding="utf-8"))
CASES = REF["cases"]
TOL = 1e-9
N_CASES = 31  # rows written by fixtures/evalue-extended-reference.R; an empty file must not pass


def test_reference_fixture_has_all_cases():
    assert len(CASES) == N_CASES, len(CASES)
    assert len({c["id"] for c in CASES}) == N_CASES
    assert {c["fun"] for c in CASES} == {"evalues.RR", "evalues.OR", "evalues.HR", "evalues.MD", "evalues.OLS", "evalues.RD"}


def _close(a, b):
    if b is None:
        return a is None
    return a is not None and abs(a - b) / max(1.0, abs(b)) <= TOL


def _ci_expected(case):
    """EValue reports the E-value of the limit nearest the true value in
    `lower` (estimate above / equal to the true value) or `upper` (below)."""
    e = case["expected"]
    return e["lower"] if e.get("lower") is not None else e.get("upper")


def _engine(expr):
    r = subprocess.run([NODE, "-e", "const E=require('./shared/evalue.js');console.log(JSON.stringify(" + expr + "));"],
                       capture_output=True, text=True, timeout=60, cwd=str(ROOT))
    if r.returncode != 0:
        raise AssertionError(r.stdout + r.stderr)
    return json.loads(r.stdout.strip().splitlines()[-1])


def _engine_call(c):
    j = json.dumps
    if c["fun"] in ("evalues.RR", "evalues.OR", "evalues.HR"):
        return f"E.eValues({j(c['measure'])},{j(c['point'])},{j(c['lo'])},{j(c['hi'])},{{rare:{j(c['rare'])},true:{j(c['true'])}}})"
    if c["fun"] == "evalues.MD":
        return f"E.eValues('SMD',{j(c['point'])},null,null,{{se:{j(c['se'])},true:{j(c['true'])}}})"
    if c["fun"] == "evalues.OLS":
        return f"E.eValuesOLS({j(c['point'])},{j(c['se'])},{j(c['sd'])},{j(c['delta'])},{{true:{j(c['true'])}}})"
    return f"E.eValuesRD({c['n11']},{c['n10']},{c['n01']},{c['n00']},{{true:{j(c['true'])}}})"


@pytest.mark.parametrize("case", CASES, ids=[c["id"] for c in CASES])
def test_engine_matches_evalue(case):
    out = _engine(_engine_call(case))
    assert _close(out["point"], case["expected"]["point"]), (out, case["expected"])
    has_ci = case["fun"] == "evalues.RD" or case.get("lo") is not None or case.get("se") is not None
    if has_ci:
        assert _close(out["ci"], _ci_expected(case)), (out, case["expected"])
    else:
        assert out["ci"] is None, out
    if case["fun"] != "evalues.RD":  # EValue's lower/upper placement, checked separately
        assert _close(out["lower"], case["expected"]["lower"]), (out, case["expected"])
        assert _close(out["upper"], case["expected"]["upper"]), (out, case["expected"])
    rr = case["expected"].get("rr")
    if rr is not None:
        assert _close(out["rr"]["point"], rr["point"]), (out, rr)
        if has_ci:
            assert _close(out["rr"]["lo"], rr["lo"]) and _close(out["rr"]["hi"], rr["hi"]), (out, rr)


def _page(cases):
    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False, encoding="utf-8") as f:
        json.dump(cases, f)
    try:
        r = subprocess.run([NODE, str(HERE / "page_driver.cjs"), f.name], capture_output=True, text=True,
                           timeout=120, cwd=str(ROOT))
    finally:
        Path(f.name).unlink()
    if r.returncode != 0:
        raise AssertionError(r.stdout + r.stderr)
    return json.loads(r.stdout)


def _page_input(c):
    if c["fun"] == "evalues.RD":
        return dict(measure="RD", n11=c["n11"], n10=c["n10"], n01=c["n01"], n00=c["n00"], truev=c["true"])
    if c["fun"] == "evalues.OLS":
        return dict(measure="OLS", point=c["point"], se=c["se"], sd=c["sd"], delta=c["delta"], truev=c["true"])
    if c["fun"] == "evalues.MD":
        return dict(measure="SMD", point=c["point"], se=c["se"], truev=c["true"])
    return dict(measure=c["measure"], point=c["point"], lo=c["lo"], hi=c["hi"], rare=c["rare"], truev=c["true"])


def test_page_matches_evalue():
    rows = _page([_page_input(c) for c in CASES])
    assert len(rows) == len(CASES) == N_CASES, len(rows)
    for case, row in zip(CASES, rows):
        assert row["accepted"], (case["id"], row["refusal"])
        res = row["result"]
        assert _close(res["point"], case["expected"]["point"]), (case["id"], res)
        has_ci = case["fun"] == "evalues.RD" or case.get("lo") is not None or case.get("se") is not None
        assert (_close(res["ci"], _ci_expected(case)) if has_ci else res["ci"] is None), (case["id"], res)


def test_page_blank_new_fields_leave_paper22_outputs_unchanged():
    # Blank "true value" and SE must reproduce the pre-extension engine bit for bit:
    # expected values were computed with shared/evalue.js at allmeta origin/main 781417ef.
    legacy = json.loads((HERE / "fixtures" / "evalue-legacy-origin-main.json").read_text(encoding="utf-8"))["cases"]
    rows = _page([dict(measure=c["measure"], point=c["point"], lo=c["lo"], hi=c["hi"], rare=c["rare"]) for c in legacy])
    for c, row in zip(legacy, rows):
        res = row["result"]
        assert res is not None, (c, row["refusal"])
        assert res["point"] == c["expected"]["point"] and res["rr"] == c["expected"]["rr"], (c, res)
        assert res["ci"] == c["expected"]["ci"], (c, res)


def test_rd_grid_is_bounded():
    # A huge bias factor would need billions of grid steps (R's seq() refuses past
    # .Machine$integer.max); the page refuses instead of freezing.
    r = subprocess.run([NODE, "-e", "const E=require('./shared/evalue.js');const t=Date.now();"
                        "try{E.eValuesRD(500000,500000,1,999999);console.log('accepted')}catch(e){console.log(e.name+' '+(Date.now()-t))}"],
                       capture_output=True, text=True, timeout=60, cwd=str(ROOT))
    name, ms = r.stdout.split()
    assert name == "RangeError" and int(ms) < 2000, r.stdout + r.stderr


@pytest.mark.parametrize("inp,why", [
    (dict(measure="OLS", point=2, lo=1.5, hi=2.7), "OLS with a CI but no outcome SD"),
    (dict(measure="OLS", point=2, se=0.5), "OLS without outcome SD"),
    (dict(measure="OLS", point=2, se=0.5, sd=0), "OLS with SD 0"),
    (dict(measure="OLS", point=2, se=-0.5, sd=3), "negative SE"),
    (dict(measure="SMD", point=0.5, lo=0.3, hi=0.7, se=0.1), "both CI and SE"),
    (dict(measure="RR", point=2, lo=1.5, hi=2.7, truev=-1), "impossible true ratio"),
    (dict(measure="RD", n11=10, n10=90, n01=20, n00=80), "negative risk difference (relabel exposure)"),
    (dict(measure="RD", n11=40, n10=60, n01=20, n00=80, truev=0.3), "true RD above estimate"),
    (dict(measure="RD", n11=40, n10=60, n01=-1, n00=80), "negative count"),
    (dict(measure="RD", n11=40, n10=60, n01=20), "missing count"),
    # Reversed limits that exclude the estimate: exp(0.91*d) rounds all three to RR 1,
    # so the order must be checked on the d scale, before conversion.
    (dict(measure="SMD", point=0, lo=1e-20, hi=-1e-20, truev=0), "reversed SMD limits that round to RR 1"),
    (dict(measure="SMD", point=0, lo=1e-20, hi=2e-20, truev=0), "SMD limits excluding the estimate, rounding to RR 1"),
])
def test_page_refuses_invalid_new_inputs(inp, why):
    row = _page([inp])[0]
    assert not row["accepted"], (why, row)
    assert row["refusal"].startswith("Analysis refused:"), row


@pytest.mark.parametrize("call,msg", [
    ("E.eValues('SMD',0,1e-20,-1e-20,{true:0})", "Lower confidence limit should be less than upper confidence limit."),
    ("E.eValues('SMD',0,1e-20,2e-20,{true:0})", "Point estimate should be inside confidence interval."),
    ("E.eValues('HR',1,1+1e-15,1+2e-15,{true:1})", "Point estimate should be inside confidence interval."),
    ("E.eValuesRD(40,60,20,80,{grid:-1})", "grid"),
    ("E.eValuesRD(40,60,20,80,{grid:NaN})", "grid"),
    ("E.eValuesRD(40,60,20,80,{grid:0})", "grid"),
])
def test_engine_refuses_before_conversion(call, msg):
    r = subprocess.run([NODE, "-e", "const E=require('./shared/evalue.js');try{const o=" + call + ";console.log('accepted '+JSON.stringify(o))}catch(e){console.log(e.name+': '+e.message)}"],
                       capture_output=True, text=True, timeout=60, cwd=str(ROOT))
    out = r.stdout.strip()
    assert out.startswith("RangeError: ") and msg in out, out + r.stderr


# EValue 4.1.4 / R 4.6.0 (Codex review of #513): evalues.RD returns lower.Evalue = 1 before it
# ever consults grid when the CI includes the true value, and seq(1, est.BF, grid) with an
# infinite (or oversized) step is not an error -- it yields no usable grid point, so lower.Evalue
# is NA. R: evalues.RD(4,6,2,8,grid=g) -> 3.4142135623730949, 1 for g in -1, NaN, 0, Inf;
# evalues.RD(40,60,20,80,grid=g) -> 3.4142135623730949, NA for g in Inf, -Inf, 10, 1e300.
@pytest.mark.parametrize("call,ci", [
    ("E.eValuesRD(4,6,2,8,{grid:-1})", 1), ("E.eValuesRD(4,6,2,8,{grid:NaN})", 1),
    ("E.eValuesRD(4,6,2,8,{grid:0})", 1), ("E.eValuesRD(4,6,2,8,{grid:Infinity})", 1),
    ("E.eValuesRD(40,60,20,80,{grid:Infinity})", None), ("E.eValuesRD(40,60,20,80,{grid:-Infinity})", None),
    ("E.eValuesRD(40,60,20,80,{grid:10})", None), ("E.eValuesRD(40,60,20,80,{grid:1e300})", None),
])
def test_rd_grid_follows_r_order(call, ci):
    r = subprocess.run([NODE, "-e", "const E=require('./shared/evalue.js');try{const o=" + call + ";console.log(JSON.stringify([o.point,o.ci]))}catch(e){console.log(e.name+': '+e.message)}"],
                       capture_output=True, text=True, timeout=60, cwd=str(ROOT))
    out = r.stdout.strip()
    assert out.startswith("["), out + r.stderr
    point, got = json.loads(out)
    assert abs(point - 3.4142135623730949) < 1e-12, out
    assert got == ci, out


def test_se_is_for_differences_only():
    # Engine: an SE with a ratio measure is refused (EValue has no SE argument for RR/OR/HR).
    r = subprocess.run([NODE, "-e", "const E=require('./shared/evalue.js');try{E.eValues('RR',2,null,null,{se:0.1});console.log('accepted')}catch(e){console.log(e.name)}"],
                       capture_output=True, text=True, timeout=60, cwd=str(ROOT))
    assert r.stdout.strip() == "RangeError", r.stdout + r.stderr
    # Page: the SE field is hidden for ratio measures, so a stale value there is ignored.
    rows = _page([dict(measure="RR", point=2, lo=1.5, hi=2.7, se=0.1), dict(measure="RR", point=2, lo=1.5, hi=2.7)])
    assert rows[0]["accepted"] and rows[0]["result"] == rows[1]["result"]


def test_field_groups_follow_measure():
    rows = _page([dict(measure="RR", point=2), dict(measure="OLS", point=2, se=1, sd=3), dict(measure="RD", n11=4, n10=6, n01=2, n00=8)])
    rr, ols, rd = (r["hidden"] for r in rows)
    assert rr["grp-rd"] and rr["grp-reg"] and not rr["grp-lo"] and not rr["grp-point"]
    assert not ols["grp-reg"] and not ols["grp-sd"] and ols["grp-lo"] and ols["grp-rd"]
    assert not rd["grp-rd"] and rd["grp-point"] and rd["grp-reg"]
