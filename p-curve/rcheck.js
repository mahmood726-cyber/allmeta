/* p-curve/rcheck.js — "Download R script" and "Verify in R (WebR)" for p-curve.
 *
 * Both controls use ONE script, generated from the inputs of the LAST analysis
 * shown on the page (window._almLastPcurve()), so R recomputes exactly what the
 * page displays. The script prints every displayed quantity next to the page's
 * value and |difference|, then an honest `MATCH n/n` or `MISMATCH m/n` line.
 * Tolerance per quantity = half a unit of the page's displayed precision
 * (fmt(x, 2) -> 0.005, fmt(x, 3) -> 0.0005; k is compared exactly).
 *
 * R reference (as in the P25 validation): base-R p-curve formulas (Simonsohn et
 * al. 2014; p-curve app 4.x) and puniform 0.2.8 for p-uniform. puniform is not in
 * the pinned same-origin WebR repository, so in the browser the five p-uniform
 * quantities are reported as NOT CHECKED (never as a pass); the downloaded
 * script checks them in desktop R with puniform installed.
 * WebR is the unchanged shared/webr-runner.js (window.AlmWebR.runR).
 */
(function (global) {
  "use strict";
  function rnum(x) { return (typeof x === "number" && Number.isFinite(x)) ? String(x) : "NA"; }

  // Which test family the LAST analysis used: run() stores it in flat_family.
  function familyOf(A) {
    var m = /^non-central t, df=(\d+)$/.exec(String(A.flat_family || ""));
    return m ? { t: true, df: parseInt(m[1], 10) } : { t: false, df: null };
  }

  function buildScript(A) {
    if (!A || !Array.isArray(A.p_values_used) || A.p_values_used.length < 3) {
      throw new Error("Run the analysis first (at least 3 significant p-values).");
    }
    var fam = familyOf(A);
    var page = [
      ["k", A.k, 0], ["fisher_chisq", A.fisher_chisq, 0.005], ["fisher_p", A.fisher_p, 0.0005],
      ["skew_full_z", A.skew_full_z, 0.005], ["skew_full_p", A.skew_full_p, 0.0005],
      ["skew_half_z", A.skew_half_z, 0.005], ["skew_half_p", A.skew_half_p, 0.0005],
      ["ncp33", A.ncp33, 0.005],
      ["flat_full_z", A.flat_full_z, 0.005], ["flat_full_p", A.flat_full_p, 0.0005],
      ["flat_half_z", A.flat_half_z, 0.005], ["flat_half_p", A.flat_half_p, 0.0005],
      ["pu_est", A.pu_est, 0.0005], ["pu_ci_lb", A.pu_ci_lb, 0.0005], ["pu_ci_ub", A.pu_ci_ub, 0.0005],
      ["pu_L0", A.pu_L0, 0.0005], ["pu_pval0", A.pu_pval0, 0.0005]
    ];
    var L = [];
    L.push("# p-curve & p-uniform: R check of the allmeta p-curve page");
    L.push("# Generated by allmeta p-curve from the inputs of the analysis shown on the page.");
    L.push("# p-curve tests: base-R formulas (Simonsohn, Nelson & Simmons 2014; p-curve app 4.x),");
    L.push("#   written out below. p-uniform: puniform 0.2.8 (van Assen, van Aert & Wicherts 2015).");
    L.push("# Tolerance: half a unit of the page's displayed precision. Run: Rscript pcurve-check.R");
    L.push("");
    L.push("p <- c(" + A.p_values_used.map(rnum).join(", ") + ")   # two-sided p-values with 0 < p < .05 (as used by the page)");
    L.push("test_family <- " + (fam.t ? '"t"' : '"z"') + "   # family for the 33%-power flatness test");
    L.push("df <- " + (fam.t ? String(fam.df) : "NA") + "   # common df (t family only)");
    L.push("");
    L.push("# Values the page displayed (full precision), and display tolerances");
    L.push("page <- c(" + page.map(function (r) { return r[0] + " = " + rnum(r[1]); }).join(",\n          ") + ")");
    L.push("tol  <- c(" + page.map(function (r) { return r[0] + " = " + String(r[2]); }).join(", ") + ")");
    L.push("");
    L.push("k <- length(p); half <- p[p < 0.025]; kh <- length(half)");
    L.push("pbound <- function(x) pmin(pmax(x, 2.2e-16), 1 - 2.2e-16)   # as the p-curve app 4.x");
    L.push("stouffer <- function(pp) sum(qnorm(pp)) / sqrt(length(pp))");
    L.push("if (test_family == \"t\") {");
    L.push("  S2 <- function(x, m) pt(x, df, ncp = m, lower.tail = FALSE) + pt(-x, df, ncp = m)");
    L.push("  crit <- function(pc) qt(pc / 2, df, lower.tail = FALSE)");
    L.push("} else {");
    L.push("  S2 <- function(x, m) pnorm(x - m, lower.tail = FALSE) + pnorm(-x - m)");
    L.push("  crit <- function(pc) qnorm(pc / 2, lower.tail = FALSE)");
    L.push("}");
    L.push("r <- c()");
    L.push("r[\"k\"] <- k");
    L.push("# Right skew, Fisher (2014): chi2 = -2 sum ln(p/.05) on 2k df");
    L.push("r[\"fisher_chisq\"] <- -2 * sum(log(p / 0.05))");
    L.push("r[\"fisher_p\"] <- pchisq(r[[\"fisher_chisq\"]], 2 * k, lower.tail = FALSE)");
    L.push("# Right skew, Stouffer (app 4.x): pp = 20p (full), 40p (half, p < .025)");
    L.push("r[\"skew_full_z\"] <- stouffer(pbound(20 * p)); r[\"skew_full_p\"] <- pnorm(r[[\"skew_full_z\"]])");
    L.push("r[\"skew_half_z\"] <- if (kh) stouffer(pbound(40 * half)) else NA");
    L.push("r[\"skew_half_p\"] <- if (kh) pnorm(r[[\"skew_half_z\"]]) else NA");
    L.push("# 33%-power flatness: ncp giving two-sided power 1/3 at alpha = .05");
    L.push("ncp <- uniroot(function(m) S2(crit(0.05), m) - 1/3, c(0, 40), tol = 1e-14)$root");
    L.push("r[\"ncp33\"] <- ncp");
    L.push("r[\"flat_full_z\"] <- stouffer(pbound(1 - S2(crit(p), ncp) / S2(crit(0.05), ncp)))");
    L.push("r[\"flat_full_p\"] <- pnorm(r[[\"flat_full_z\"]])");
    L.push("r[\"flat_half_z\"] <- if (kh) stouffer(pbound(1 - S2(crit(half), ncp) / S2(crit(0.025), ncp))) else NA");
    L.push("r[\"flat_half_p\"] <- if (kh) pnorm(r[[\"flat_half_z\"]]) else NA");
    L.push("# p-uniform: puniform(yi = z, vi = 1, side = \"right\", method = \"P\"), z = qnorm(1 - p/2)");
    L.push("pu_names <- c(\"pu_est\", \"pu_ci_lb\", \"pu_ci_ub\", \"pu_L0\", \"pu_pval0\")");
    L.push("have_pu <- suppressWarnings(requireNamespace(\"puniform\", quietly = TRUE))");
    L.push("if (have_pu) {");
    L.push("  pu <- puniform::puniform(yi = qnorm(1 - p / 2), vi = rep(1, k), side = \"right\", method = \"P\")");
    L.push("  num1 <- function(x) if (length(x) == 1 && is.numeric(x)) as.numeric(x) else NA");
    L.push("  r[pu_names] <- c(num1(pu$est), num1(pu$ci.lb), num1(pu$ci.ub), num1(pu$L.0), num1(pu$pval.0))");
    L.push("}");
    L.push("");
    L.push("check <- names(page); if (!have_pu) check <- setdiff(check, pu_names)");
    L.push("ok <- logical(0)");
    L.push("cat(sprintf(\"%-13s %20s %20s %10s  %s\\n\", \"quantity\", \"page\", \"R\", \"|diff|\", \"\"))");
    L.push("for (q in check) {");
    L.push("  a <- page[[q]]; b <- r[[q]]");
    L.push("  good <- if (is.na(a) || is.na(b)) (is.na(a) && is.na(b)) else abs(a - b) <= tol[[q]]");
    L.push("  ok[q] <- good");
    L.push("  cat(sprintf(\"%-13s %20.12g %20.12g %10.3g  %s\\n\", q, a, b, if (is.na(a) || is.na(b)) NA else abs(a - b), if (good) \"ok\" else \"DIFFERS\"))");
    L.push("}");
    L.push("if (!have_pu) cat(\"NOT CHECKED: \", paste(pu_names, collapse = \", \"), \" -- package puniform is not installed in this R\\n\", sep = \"\")");
    L.push("cat(R.version.string, if (have_pu) paste0(\"; puniform \", packageVersion(\"puniform\")) else \"; puniform not installed\", \"\\n\", sep = \"\")");
    L.push("n <- length(ok); m <- sum(ok)");
    L.push("cat(if (m == n && n > 0) sprintf(\"MATCH %d/%d\", m, n) else sprintf(\"MISMATCH %d/%d\", m, n),");
    L.push("    if (!have_pu) sprintf(\" (%d p-uniform quantities NOT CHECKED: package puniform not available)\", length(pu_names)) else \"\", \"\\n\", sep = \"\")");
    return L.join("\n") + "\n";
  }

  function current() { return typeof global._almLastPcurve === "function" ? global._almLastPcurve() : null; }

  function download() {
    var txt = buildScript(current());
    var blob = new Blob([txt], { type: "text/x-r;charset=utf-8" });
    var url = URL.createObjectURL(blob), a = document.createElement("a");
    a.href = url; a.download = "pcurve-check.R";
    document.body.appendChild(a); a.click();
    setTimeout(function () { document.body.removeChild(a); URL.revokeObjectURL(url); }, 0);
    return txt;
  }

  var verifyGen = 0;
  var STALE = "R result discarded: the analysis on the page changed while R was running, so the verdict R returned (for the earlier analysis) is not shown. Press Verify in R again.";
  async function verify() {
    var out = document.getElementById("rcheck-out"), st = document.getElementById("rcheck-status");
    var btn = document.getElementById("btn-rverify");
    var set = function (t) { if (st) st.textContent = t; };
    var script, snap = current();
    try { script = buildScript(snap); } catch (e) { set(e.message); return; }
    var my = ++verifyGen;   // a later Verify, or a re-run of the analysis, makes this run's answer stale
    if (!global.AlmWebR || typeof global.AlmWebR.runR !== "function") { set("WebR runner (../shared/webr-runner.js) did not load; use Download R script."); return; }
    if (btn) btn.disabled = true;
    out.textContent = "";
    set("Starting WebR (first run downloads R, about a minute)... Note: package puniform is not in the pinned WebR repository, so the 5 p-uniform quantities are NOT CHECKED here; the downloaded script checks them in desktop R.");
    var res = await global.AlmWebR.runR({ script: script, packages: [], onStatus: function (t) { set(t); } });
    if (btn) btn.disabled = false;
    // R answered for the analysis it was given; if the page has moved on, never show that answer beside the new one.
    if (my !== verifyGen || current() !== snap) { out.textContent = ""; set(STALE); return; }
    if (!res.ok) { set("WebR failed: " + res.error); return; }
    out.textContent = res.stdout;
    var last = (res.stdout.match(/^(MATCH|MISMATCH).*$/m) || ["(no MATCH line in R output)"])[0];
    set("R finished (" + res.versions.R + ", webR " + res.versions.webR + "): " + last);
  }

  global.PCurveRCheck = { buildScript: buildScript, download: download, verify: verify };
  // Loaded at the end of <body>, so the controls already exist: bind directly.
  if (typeof document !== "undefined" && typeof document.getElementById === "function") {
    var d = document.getElementById("btn-rscript"), v = document.getElementById("btn-rverify");
    if (d) d.addEventListener("click", function () {
      try { download(); } catch (e) { var st = document.getElementById("rcheck-status"); if (st) st.textContent = e.message; }
    });
    if (v) v.addEventListener("click", verify);
  }
})(typeof window !== "undefined" ? window : globalThis);
